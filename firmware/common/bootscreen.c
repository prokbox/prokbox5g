#include "config.h"
#include <stdint.h>
#include <string.h>
#include "lcd.h"
#include "bootscreen.h"

#if LCD_DEPTH != 16 || LCD_WIDTH != 320 || LCD_HEIGHT != 240
#error "bootscreen: the generated data is for a 320x240 RGB565 panel"
#endif

void bootscreen_draw(void)
{
    /* gradient: two dithered colours per row, as one 32-bit word (even x in
     * the low half: little-endian) stored LCD_WIDTH/2 times */
    for (int y = 0; y < LCD_HEIGHT; y++)
    {
        uint32_t *dst = (uint32_t *)FBADDR(0, y);
        uint32_t two = bootscreen_bg[y][0] | (uint32_t)bootscreen_bg[y][1] << 16;
        for (int n = LCD_WIDTH / 2; n > 0; n--)
            *dst++ = two;
    }

    /* the glyph: an opaque block pre-composited onto the same gradient */
    const unsigned short *src = bootscreen_block;
    for (int y = 0; y < BOOTSCREEN_H; y++, src += BOOTSCREEN_W)
        memcpy(FBADDR(BOOTSCREEN_X, BOOTSCREEN_Y + y), src,
               BOOTSCREEN_W * sizeof(*src));
}
