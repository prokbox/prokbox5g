    .syntax unified
    .arm
    .text
    .global _start
_start:
    ldr sp, =0x00100000
    bl main
    /* ARM semihosting SYS_EXIT (0x18), ADP_Stopped_ApplicationExit */
    mov r0, #0x18
    ldr r1, =exit_block
    svc 0x123456
hang:
    b hang
    .align 2
exit_block:
    .word 0x20026
    .word 0
