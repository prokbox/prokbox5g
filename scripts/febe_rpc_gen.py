"""The UI boundary's remote calls (P19 S3): generate the stubs.

usage: scripts/febe_rpc_gen.py [--check] [--from-build BUILD_DIR]

apps/ipodui/febe_rpc.list names every back-end function the shell calls
directly (one per line; '#' comments).  For each, the linker's --wrap sends
every caller to a 5-instruction stub (apps/ipodui/febe_rpc_stubs.S): on the
CPU it jumps straight to the real function, arguments untouched; on the
COP it hands the call to be_svc on the CPU (fe_be.c, febe_remote_c()), with
the cache operations of a be_call.  apps/ipodui/febe_rpc.opts carries the
--wrap options (apps/apps.make adds it to the developer firmware's link).

Limits (checked by review, listed in the file): at most 12 argument words
(4 in registers, 8 on the stack), a 64-bit or smaller result, no callback
that the back end later runs on the COP's behalf.

--from-build BUILD_DIR adds to the list what febe_link_check.py finds the
shell's objects calling in that build (back-end families and the shell's
CPU-only objects), keeping comments and the "direct:" lines.  --check exits 1 when
the generated files are out of date.
"""
import os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIST = os.path.join(ROOT, 'apps/ipodui/febe_rpc.list')
STUBS = os.path.join(ROOT, 'apps/ipodui/febe_rpc_stubs.S')
OPTS = os.path.join(ROOT, 'apps/ipodui/febe_rpc.opts')

HEADER = '''/***************************************************************************
 *              __________                   __    __________
 *   Open       \\______   \\_______    ____  |  | __\\______   \\  ____  ___  ___
 *   Source      |     ___/\\_  __ \\  /  _ \\ |  |/ / |    |  _/ /  _ \\ \\  \\/  /
 *   Player      |    |     |  | \\/ (  <_> )|    <  |    |   \\(  <_> ) >    <
 *   Firmware    |____|     |__|     \\____/ |__|_ \\ |______  / \\____/ /__/\\_ \\
 *                                               \\/        \\/               \\/
 *
 * Custom firmware for the iPod Video, 5th generation (5G and 5.5G).
 * Not affiliated with or endorsed by Apple Inc.
 *
 * The UI boundary's remote-call stubs (P19 S3).  GENERATED by
 * scripts/febe_rpc_gen.py from apps/ipodui/febe_rpc.list: do not edit.
 *
 * Copyright (C) 2026 prokopto-dev
 *
 * This program is free software; you can redistribute it and/or
 * modify it under the terms of the GNU General Public License
 * as published by the Free Software Foundation; either version 2
 * of the License, or (at your option) any later version.
 *
 * This software is distributed on an "AS IS" basis, WITHOUT WARRANTY OF ANY
 * KIND, either express or implied.
 *
 ****************************************************************************/
'''

BODY = '''#include "config.h"

/* Every stub: PROCESSOR_ID (0x60000000) reads 0x55 on the CPU.  The CPU
 * goes straight to the real function (r0-r3 and the stack untouched, the
 * flags only); the COP goes to febe_remote with ip = the real function.
 * Each stub sits in its own section so --gc-sections drops the ones this
 * build never calls; __real_* is weak for the same reason. */
    .macro FEBE_STUB name
    .section .text.__wrap_\\name, "ax", %progbits
    .align 2
    .global __wrap_\\name
    .type __wrap_\\name, %function
    .weak __real_\\name
__wrap_\\name:
    mov     ip, #0x60000000
    ldrb    ip, [ip]
    cmp     ip, #0x55
    ldr     ip, =__real_\\name
    bxeq    ip
    b       febe_remote
    .ltorg
    .size __wrap_\\name, . - __wrap_\\name
    .endm

/* The COP: r0-r3 and the caller's first eight stack words go to
 * febe_remote_c(fn, words) (fe_be.c), which returns the result in r0:r1 */
    .section .text.febe_remote, "ax", %progbits
    .align 2
    .global febe_remote
    .type febe_remote, %function
febe_remote:
    stmfd   sp!, {r4-r7, lr}        @ 20 bytes
    sub     sp, sp, #52             @ words[12] at sp (+4 keeps 8-alignment)
    stmia   sp, {r0-r3}             @ words[0..3]: the register arguments
    add     r4, sp, #72             @ r4 = the caller's sp: its stack args
    ldmia   r4!, {r0-r3}
    add     r5, sp, #16
    stmia   r5!, {r0-r3}            @ words[4..7]
    ldmia   r4, {r0-r3}
    stmia   r5, {r0-r3}             @ words[8..11]
    mov     r0, ip                  @ fn
    mov     r1, sp                  @ words
    bl      febe_remote_c           @ r0:r1 = the result
    add     sp, sp, #52
    ldmfd   sp!, {r4-r7, lr}
    bx      lr
    .size febe_remote, . - febe_remote

/* be_svc (CPU): uint64_t febe_invoke(void *fn, const uint32_t *w): calls
 * fn with r0-r3 = w[0..3] and w[4..11] as its first eight stack words */
    .section .text.febe_invoke, "ax", %progbits
    .align 2
    .global febe_invoke
    .type febe_invoke, %function
febe_invoke:
    stmfd   sp!, {r4, r5, r6, lr}
    mov     r4, r0
    mov     r5, r1
    sub     sp, sp, #32             @ the callee's eight stack words
    add     r0, r5, #16
    ldmia   r0, {r0-r3}
    stmia   sp, {r0-r3}
    add     r0, r5, #32
    ldmia   r0, {r0-r3}
    add     r6, sp, #16
    stmia   r6, {r0-r3}
    ldmia   r5, {r0-r3}
    mov     lr, pc
    bx      r4
    add     sp, sp, #32
    ldmfd   sp!, {r4, r5, r6, lr}
    bx      lr
    .size febe_invoke, . - febe_invoke

'''


def read_list():
    syms = []
    for l in open(LIST):
        l = l.split('#', 1)[0].strip()
        if l and not l.startswith('direct:'):
            syms.append(l)
    return syms


def render(syms):
    s = HEADER + BODY
    for n in syms:
        s += '    FEBE_STUB %s\n' % n
    # --undefined pulls each real function's archive member into the link:
    # with every reference redirected to __wrap_X, nothing else references
    # X, and a weak __real_X alone never extracts it, so it resolved to 0
    # (fdprintf, power_sleep; the 207956fb84 storage-thread hang)
    o = ''.join('-Wl,--wrap=%s\n-Wl,--undefined=%s\n' % (n, n)
                for n in syms)
    return s, o


def main(argv):
    if '--from-build' in argv:
        b = argv[argv.index('--from-build') + 1]
        sys.path.insert(0, os.path.join(ROOT, 'scripts'))
        import febe_link_check as lc
        keep = [l for l in open(LIST)] if os.path.exists(LIST) else []
        direct = {l.split(':', 1)[1].strip() for l in keep
                  if l.startswith('direct:')}
        # a union: each build flavour (fw-ui, the developer combined build,
        # modules) adds what it references; stubs a build never calls are
        # dropped by --gc-sections (weak __real_*)
        old = {l.strip() for l in keep
               if l.strip() and not l.startswith(('#', 'direct:'))}
        # data never wraps (p19-bssfix): a listed object is dropped here
        # and failed by febe_link_check.py; it crosses by a getter
        syms = sorted((old | lc.referenced(b)) - direct - lc.data_objects(b))
        head = [l for l in keep if l.startswith('#') or
                l.startswith('direct:')]
        with open(LIST, 'w') as f:
            f.writelines(head)
            for n in syms:
                f.write(n + '\n')
    syms = read_list()
    s, o = render(syms)
    if '--check' in argv:
        ok = (os.path.exists(STUBS) and open(STUBS).read() == s and
              os.path.exists(OPTS) and open(OPTS).read() == o)
        print('febe rpc: %d stubs, %s' % (len(syms),
                                           'in date' if ok else 'OUT OF DATE'))
        return 0 if ok else 1
    open(STUBS, 'w').write(s)
    open(OPTS, 'w').write(o)
    print('febe rpc: %d stubs written' % len(syms))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
