"""The Bench session's owner's script, generated from the firmware's source.

apps/ipodui/devbench.c (the step table, the fixed screens' macros),
apps/ipodui/devbench_power.c (the battery rows' phase screen and
questions) and apps/ipodui/devbench.h (the re-verify and port-check picks)
hold every text the session shows.  This tool lays them out as the device
does (word-wrapped to WRAP_WIDTH by bench_next_line's rule, the buttons
added) and writes the result into docs/research/bcm2722/bench-p19.md
between the "owner-script" markers, so the doc and the code can't drift.

  python3 scripts/bench_script.py --write   regenerate the doc section
  python3 scripts/bench_script.py --check   exit 1 if the doc differs or a
                                            screen doesn't fit (the test)
  python3 scripts/bench_script.py           print the section

The fit check: every screen's text lines fit SCR_MAX (more would be cut on
the device), every line WRAP_WIDTH characters, every list (text, buttons,
answers) the rows one screen shows without scrolling (LIST_ROWS), and the
list's text the simplelist buffer (SIMPLELIST_MAX_LINES lines of
SIMPLELIST_MAX_LINELENGTH bytes).  The words check (sitting 4c's rules, on
every screen of the re-verify run and the fixed screens): no step codes,
2 to 4 answers a question, no "Rockbox" or hidden-folder name, UK
spelling.

The doc assumes the build A configuration (--bcmfw-video ... --bcmfw-merged):
HAVE_BCMFW_RESIDENT and HAVE_BCM_JOBS on, so every table entry is in.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import bench_ingest as bi  # noqa: E402

DOC = os.path.join(ROOT, 'docs/research/bcm2722/bench-p19.md')
BEGIN = '<!-- owner-script: generated by scripts/bench_script.py; do not edit -->'
END = '<!-- owner-script: end -->'

# The screen (apps/gui/list.h, the 320 x 240 panel with the 8 px system
# font the developer screens use: a title row, then 28 list rows)
LIST_ROWS = 28
SIMPLELIST_MAX_LINES = 32
SIMPLELIST_MAX_LINELENGTH = 48      # HAVE_ATA_SMART (ipodvideo.h)
PHASE_ROWS = 30                     # lcd_puts rows on the phase screen


def read(rel):
    with open(os.path.join(ROOT, rel)) as f:
        return f.read()


def c_unescape(s):
    return s.encode('latin-1').decode('unicode_escape')


def macros(src):
    """#define NAME "..." (adjacent literals joined, line continuations
    followed) and #define NAME <number>"""
    out = {}
    src = src.replace('\\\n', ' ')
    for m in re.finditer(r'^#define\s+(\w+)\s+(.*)$', src, re.M):
        body = bi.strip_comments(m.group(2)).strip()
        lits = re.findall(r'"((?:[^"\\]|\\.)*)"', body)
        if lits and body.startswith('"'):
            out[m.group(1)] = c_unescape(''.join(lits))
        elif re.fullmatch(r'\d+', body.split()[0] if body.split() else ''):
            out[m.group(1)] = int(body.split()[0])
    return out


def c_array(src, name):
    m = re.search(r"%s\[[^\]]*\]\s*=\s*\{(.*?)\};" % re.escape(name), src, re.S)
    if not m:
        raise ValueError('no %s[] in the source' % name)
    body = bi.strip_comments(m.group(1))
    return [c_unescape(x) for x in re.findall(r'"((?:[^"\\]|\\.)*)"', body)]


def wrap(text, width):
    """bench_next_line's rule (devbench.h)"""
    lines, p = [], text or ''
    while p:
        n = p.find('\n')
        n = len(p) if n < 0 else n
        if n <= width:
            lines.append(p[:n])
            p = p[n + 1:] if n < len(p) else ''
            continue
        k = width
        while k > 0 and p[k] != ' ':
            k -= 1
        if k == 0:
            k = width
        lines.append(p[:k].rstrip(' '))
        p = p[k:].lstrip(' ')
    return lines


def parse_table(c_src, h_src):
    """devbench.c's steps[] with every field (bench_ingest's parser for
    the shape, the rest here)"""
    base = bi.parse_steps(c_src, h_src)
    m = re.search(r'static const struct bench_step steps\[\]\s*=\s*\{', c_src)
    body = c_src[m.end():]
    body = bi.strip_comments(body[:body.find('\n};')])
    body = '\n'.join(ln for ln in body.split('\n')
                     if not ln.strip().startswith('#'))
    entries, depth, start, i = [], 0, 0, 0
    while i < len(body):
        c = body[i]
        if c == '"':
            j = i + 1
            while body[j] != '"':
                j += 2 if body[j] == '\\' else 1
            i = j + 1
            continue
        if c == '{':
            if depth == 0:
                start = i
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                entries.append(bi.split_top(body[start + 1:i]))
        i += 1
    assert len(entries) == len(base)
    for s, f in zip(base, entries):
        s['say'] = c_unescape(bi.cstr(f[2])) if bi.cstr(f[2]) else None
        s['say2'] = c_unescape(bi.cstr(f[3])) if bi.cstr(f[3]) else None
        s['ask'] = c_unescape(s['ask']) if s['ask'] else None
        s['fn_name'] = f[4].strip()
        s['limit'] = int(f[8], 0)
        s['budget'] = int(f[9], 0) if len(f) > 9 else 0
        s['secs'] = s['budget'] or s['limit']
    return base


class Bench:
    def __init__(self):
        self.c = read('apps/ipodui/devbench.c')
        self.h = read('apps/ipodui/devbench.h')
        self.pw = read('apps/ipodui/devbench_power.c')
        self.pwh = read('apps/ipodui/devbench_power.h')
        self.m = macros(self.c)
        self.pm = macros(self.pw)
        self.ph = macros(self.pwh)
        self.t = parse_table(self.c, self.h)
        self.picks = {bi.MODE_REVERIFY: bi.parse_pick_table(self.h, 'bench_reverify_picks'),
                      bi.MODE_PORTCHECK: bi.parse_pick_table(self.h, 'bench_portcheck_picks')}
        self.needs = bi.parse_pick_needs(self.h, 'bench_reverify_picks')
        self.gates = bi.parse_gates(self.h)
        self.gate_why = c_unescape(macros(self.h)['BENCH_GATE_WHY'])
        self.mode_answers = c_array(self.h, 'bench_mode_answers')
        self.width = self.m['WRAP_WIDTH']
        self.scr_max = self.m['SCR_MAX']
        self.problems = []

    # ---- bench_select and the sums (devbench.h) ----
    def select(self, mode):
        return bi.select(mode, self.t, self.picks.get(mode, []))

    def run_sum(self, run, which, start=0):
        secs = n = 0
        for k, role in run[start:]:
            s = self.t[k]
            opt = bool(s['flags'] & bi.F['BENCH_F_OPTIONAL'])
            ifpre = role in (bi.R_IFPRE, bi.R_IFBOOT)
            if which == 'block':
                if not s['flags'] & bi.F['BENCH_F_AUTO']:
                    break
                inside = True
            elif which == 'optional':
                inside = opt
            elif which == 'ifpre':
                inside = ifpre
            else:
                inside = not opt and not ifpre
            if inside:
                secs += s['secs']
                n += 1
        return secs, n

    @staticmethod
    def minutes(secs):
        return (secs + 59) // 60 if secs else 0

    # ---- the screens ----
    def text(self, *parts):
        """scr_add / scr_blank: None is an empty line"""
        out = []
        for p in parts:
            if p is None:
                out.append('')
            else:
                out += wrap(p, self.width)
        return out

    def screen(self, where, lines, tail):
        """text lines, then buttons or answers (tail); fit-checked"""
        if len(lines) > self.scr_max:
            self.problems.append('%s: %d text lines, the device keeps %d'
                                 % (where, len(lines), self.scr_max))
        for ln in lines:
            if len(ln) > self.width:
                self.problems.append('%s: a line over %d: %r' % (where, self.width, ln))
        items = lines[:self.scr_max] + list(tail)
        if len(items) > LIST_ROWS:
            self.problems.append('%s: %d rows, one screen shows %d'
                                 % (where, len(items), LIST_ROWS))
        if len(items) > SIMPLELIST_MAX_LINES or \
                sum(len(x) + 1 for x in items) > SIMPLELIST_MAX_LINES * SIMPLELIST_MAX_LINELENGTH:
            self.problems.append('%s: past the simplelist buffer' % where)
        self.rows_max = max(getattr(self, 'rows_max', 0), len(items))
        return items

    def go_screen(self, where, lines, menu, go):
        """menu None: no MENU line (MENU still leaves)"""
        return self.screen(where, lines, ([self.m[menu]] if menu else []) +
                           [self.m[go]])

    def ask_screen(self, where, lines, opts):
        return self.screen(where, lines, ['( ) ' + o for o in opts])

    def start_screen(self, s):
        lines = self.text(s['say'])
        if s['say2']:
            lines += self.text(None, s['say2'])
        return self.go_screen('%s start' % s['id'], lines, None,
                              'GO_START' if s['fn'] else 'GO_LEAVE')

    def question(self, s):
        opts = list(s['answers'])
        lines = self.text(s['ask'])
        if s['flags'] & bi.F['BENCH_F_GO']:
            secs = sum(x['secs'] for x in self.t if x['flags'] & bi.F['BENCH_F_OPTIONAL'])
            n = sum(1 for x in self.t if x['flags'] & bi.F['BENCH_F_OPTIONAL'])
            lines += self.text(self.m['WAVE_FMT'] % (self.minutes(secs), n))
        lines += self.text(self.m['ASK_HINT'])
        return self.ask_screen('%s question' % s['id'], lines, opts)

    def mode_screen(self):
        mins = [self.minutes(self.run_sum(self.select(k), 'main')[0])
                for k in range(3)]
        return self.ask_screen('mode question',
                               self.text(self.m['MODES_FMT'] % tuple(mins)),
                               self.mode_answers)

    def confirm_screen(self, mode):
        run = self.select(mode)
        secs, n = self.run_sum(run, 'main')
        lines = self.text(self.m['COUNT_FMT'] % (n, self.minutes(secs)))
        extra, k = self.run_sum(run, 'optional')
        if k:
            lines += self.text(self.m['WAVE2_FMT'] % self.minutes(extra))
        extra, k = self.run_sum(run, 'ifpre')
        if k:
            lines += self.text(self.m['IFPRE_FMT'] % self.minutes(extra))
        lines += self.text(None, self.m[{bi.MODE_PORTCHECK: 'PORT_TEXT',
                                          bi.MODE_REVERIFY: 'REVERIFY_TEXT'}
                                         .get(mode, 'FULL_TEXT')], None)
        if mode != bi.MODE_PORTCHECK:
            lines += self.text(self.m['STEPS_TEXT'], None)
        lines += self.text(self.m['RESTARTS_TEXT'])
        return self.go_screen('confirm %s' % bi.mode_name(mode), lines,
                              'MENU_CANCEL', 'GO_START'), n, secs

    def hands_off(self, run, p):
        secs, _ = self.run_sum(run, 'block', p)
        lim = 0
        for k, _ in run[p:]:
            if not self.t[k]['flags'] & bi.F['BENCH_F_AUTO']:
                break
            lim = max(lim, self.t[k]['limit'])
        return self.go_screen('hands off', self.text(
            self.m['HANDS_FMT'] % (self.minutes(secs), self.minutes(lim + 10))),
            None, 'GO_START')

    # ---- the words (sitting 4c) ----
    CODE_RE = re.compile(r'\b(?:PB-?\d|PW\d|[BC]\d{1,2}|[Ss]tages? \d|J_\w+|COP row)')
    US_RE = re.compile(r'\b(?:[Cc]olors?|[Cc]enter|[Gg]ray|[Bb]ehaviors?|[Aa]nalyze|'
                       r'[Ff]avorite|[Cc]anceled|[Ii]nitialize|[Vv]isualiz\w*)\b')
    PLAIN_IDS = {'pre', 'boot', 'jobs', 'port', 'scroll'}

    def words(self, where, text):
        """the owner-facing words: no step codes, no Rockbox, UK spelling"""
        if not text:
            return
        ids = {x['id'] for x in self.t} - self.PLAIN_IDS
        for w in re.findall(r'[A-Za-z0-9_-]+', text):
            if w in ids:
                self.problems.append('%s: a step code on screen: %r' % (where, w))
        for m in self.CODE_RE.finditer(text):
            self.problems.append('%s: a step code on screen: %r' % (where, m.group()))
        if re.search(r'rockbox', text, re.I):
            self.problems.append('%s: "Rockbox" or the hidden folder on screen' % where)
        m = self.US_RE.search(text)
        if m:
            self.problems.append('%s: US spelling: %r' % (where, m.group()))

    def check_words(self):
        for k, _ in self.select(bi.MODE_REVERIFY):
            s = self.t[k]
            for f in ('title', 'say', 'say2', 'ask'):
                self.words('%s %s' % (s['id'], f), s[f])
            for a in s['answers']:
                self.words('%s answer' % s['id'], a)
            if s['ask'] and not 2 <= len(s['answers']) <= 4:
                self.problems.append('%s: %d answers (2 to 4)' % (s['id'], len(s['answers'])))
        for name, v in self.m.items():
            if isinstance(v, str):
                self.words(name, v)
        for gid, (_, why) in self.gates.items():
            self.words('gate %s' % gid, why)
        self.words('BENCH_GATE_WHY', self.gate_why)

    def phase_screen(self, title, state):
        rows = [title, '', 'Phase 1 of %d (A), %d s:' % (self.ph['BPW_PHASES'],
                                                       self.ph['BPW_PHASE_S']),
                state, ''] + c_array(self.pw, 'bpw_phase_lines')
        for r in rows:
            if len(r) > self.width:
                self.problems.append('phase screen: a line over %d: %r' % (self.width, r))
        if len(rows) > PHASE_ROWS:
            self.problems.append('phase screen: %d rows' % len(rows))
        return rows


def block(lines, title=None):
    out = ['```']
    if title:
        out.append('[%s]' % title)
    out += [ln for ln in lines]
    out.append('```')
    return out


def flag_words(b, s):
    F = bi.F
    if s['flags'] & F['BENCH_F_AUTO']:
        return 'hands off'
    if s['flags'] & F['BENCH_F_GO']:
        return 'go question'
    if not s['fn']:
        return 'done outside the session'
    if not s['say']:
        return 'automatic, no screen, a moment'
    if s['flags'] & F['BENCH_F_OPTIONAL']:
        return 'wave 2 (its own screens)'
    return 'watched'


def buttons(b, s):
    """What MENU and SELECT do, from the run() rules"""
    F = bi.F
    if s['flags'] & F['BENCH_F_AUTO']:
        return ('none of its own: the "Hands off now" screen comes first '
                '(SELECT starts the checks); buttons do nothing while it runs')
    if s['flags'] & F['BENCH_F_GO']:
        return 'SELECT picks an answer; MENU skips it (= Not now)'
    if not s['say']:
        return 'none: no screen'
    parts = ['start screen: SELECT on the last line %s (no MENU line: MENU '
             'still stops the session quietly, and this step comes back at the '
             'next Resume)'
             % ('starts it' if s['fn'] else 'leaves the session to do it')]
    if s['id'] in ('slp', 'lvl5', 'lit24'):
        parts.append('in a phase: MENU ends the row early (skipped, no '
                     'question; the session goes on); SELECT and the wheel '
                     'do nothing')
    if s['flags'] & F['BENCH_F_REBOOTS']:
        parts.append('then MENU or SELECT closes the restart screen')
    if s['flags'] & F['BENCH_F_LEAVES']:
        parts.append('after arming, MENU or SELECT closes the screen')
    if s['ask']:
        parts.append('question: SELECT picks; MENU skips it')
    return '; '.join(parts)


def render():
    b = Bench()
    out = [BEGIN, '', "## Owner's script", '',
           'Generated from `apps/ipodui/devbench.c`, `devbench_power.c` and '
           '`devbench.h` by `scripts/bench_script.py` (`--write`); '
           '`tests/bench_script/run.sh` fails when this section and the code '
           'differ, or when a screen would not fit. Each block is the exact '
           'screen: the title in brackets, the text as the iPod wraps it '
           '(%d characters), then the buttons; `( )` marks an answer. '
           'Times are the steps\' budgets (`budget_s`, or the watchdog limit '
           'for a hands-off step). Build A configuration: every entry is in.'
           % b.width, '',
           '**Buttons everywhere:** a SELECT line is always the last line: '
           'scroll down to it with the wheel, then press SELECT (SELECT '
           'elsewhere does nothing). On a question, scroll to an answer and '
           'press SELECT; MENU there skips the question (recorded as "Skip"). '
           'No screen offers "run it or skip": the session decides by itself '
           '(the dependency table below). MENU on a start screen still stops '
           'the session quietly; opening Bench session again offers Resume, '
           'and that step comes back. A frozen screen: hold MENU and SELECT '
           '6 to 8 s.',
           '']
    out += ['### Opening the row', '']
    out += block(b.mode_screen(), 'Bench session')
    out += ['', 'If a session is open, this comes first instead:', '']
    resume = ['Resume after <last step>', 'Start a new session', 'Cancel']
    out += block(b.ask_screen('resume', b.text(b.m['RESUME_TEXT']), resume),
                 'Bench session')
    out += ['', '("Go on: <step>" replaces the first answer when a step you '
            'left, or the restart, is waiting for its question.)', '']

    for mode in (bi.MODE_FULL, bi.MODE_REVERIFY, bi.MODE_PORTCHECK):
        scr, n, secs = b.confirm_screen(mode)
        run = b.select(mode)
        out += ['### %s: %d steps, about %d min' % (
            b.mode_answers[mode], n, b.minutes(secs)), '']
        out += block(scr, 'Bench session')
        needs = mode == bi.MODE_REVERIFY
        out += ['', '| # | Step | Kind | Time |%s Question |' % (' Needs |' if needs else ''),
                '|---|---|---|---|%s---|' % ('---|' if needs else '')]
        for i, (k, role) in enumerate(run):
            s = b.t[k]
            q = s['ask'].split('\n')[0] if s['ask'] else '—'
            kind = flag_words(b, s)
            if role == bi.R_IFPRE:
                kind += '; only without the stage 5 flag'
            elif role == bi.R_IFBOOT:
                kind += ('; only without the stage 5 flag or without the display '
                         'driver in this start')
            elif role == bi.R_NEED and s['id'] in ('jobs', 'jvpu'):
                kind += '; must pass (a restart offered if it cannot run)'
            elif role == bi.R_NEED:
                kind += '; must pass'
            elif role == bi.R_OPT:
                kind += '; may skip, never fail'
            elif role == bi.R_ALSO:
                kind += '; not needed for the verified line'
            nd = ''
            if needs:
                nd = ' %s |' % (', '.join('`%s`' % x for x in b.needs.get(s['id'], []))
                                or '—')
            out.append('| %d | `%s` %s | %s | %s |%s %s |' % (
                i + 1, s['id'], s['title'], kind,
                '~%d min' % b.minutes(s['secs']) if s['secs'] >= 60 else
                '~%d s' % s['secs'], nd, q))
        out += ['', 'The screens between steps, in this run:', '']
        prev_auto = False
        for p, (k, role) in enumerate(run):
            auto = bool(b.t[k]['flags'] & bi.F['BENCH_F_AUTO'])
            if auto and not prev_auto and p > 0:
                out += ['Before `%s`:' % b.t[k]['id'], '']
                out += block(b.hands_off(run, p), 'Hands off now')
                out += ['']
            if not auto and prev_auto:
                out += ['Before `%s`:' % b.t[k]['id'], '']
                out += block(b.go_screen('done', b.text(
                    b.m['DONE_FMT'] % (0, 0, 0)), None, 'GO_ON'),
                    'Automatic checks done')
                out += ['', '(the counts are the session\'s so far)', '']
            prev_auto = auto
        if mode == bi.MODE_REVERIFY:
            out += ['**When a step fails** (the gates, `bench_gates[]`): the steps that '
                    'need it skip by themselves, recorded with `note=auto-skip: needs '
                    '<id> (<result>)`, and this screen shows once a gate. A gate that '
                    'ends the session skips every later step. A must-pass step that '
                    'fails never stops the session by itself: what does not need it '
                    'still runs, and the summary closes it.', '',
                    '| Gate | Ends the session | Skipped after it |', '|---|---|---|']
            for gid, (end, _) in b.gates.items():
                after = [b.t[k2]['id'] for k2, _ in run
                         if gid in b.needs.get(b.t[k2]['id'], [])]
                out.append('| `%s` | %s | %s |' % (
                    gid, 'yes' if end else 'no',
                    'every later step' if end else
                    ', '.join('`%s`' % x for x in after) or '—'))
            out += ['']
            for gid, (_, why) in b.gates.items():
                out += block(b.go_screen('skip %s' % gid, b.text(why), None, 'GO_ON'),
                             b.m['SKIP_TITLE'])
                out += ['']
            out += ['A must-pass step that could not run for a reason a restart '
                    'fixes (no display driver in this start; e.g. Chip self-test), '
                    'offered once:', '']
            out += block(b.ask_screen('retry offer', b.text(
                b.m['RETRY_FMT'] % 'Chip self-test'),
                ['Restart and retry', 'Carry on']), 'Chip self-test')
            out += ['', 'The end of the session (the counts, what did not pass by '
                    'title, the verified line when earned):', '']
            out += block(b.screen('summary', ['8 passed, 2 failed, 9 skipped'] +
                                  b.text(b.m['NOTPASS_TEXT']) +
                                  ['- Test clips', '- Screens on second core',
                                   'Not every step passed:', 'no verified line this time.'] +
                                  b.text(b.m['FINISH_TEXT']),
                                  ['MENU: leave this screen']), 'Bench session')
            out += ['', 'Stopped before the end (MENU on a screen, or left for a step '
                    'outside the session):', '']
            out += block(b.screen('stopped', ['3 passed, 0 failed, 1 skipped'] +
                                  b.text(b.m['STOPPED_TEXT']),
                                  ['MENU: leave this screen']), 'Bench session')
            out += ['']

    out += ['### Every step', '']
    for s in b.t:
        out += ['#### `%s` %s' % (s['id'], s['title']), '']
        out.append('- **Kind:** %s. **Time:** %s.' % (
            flag_words(b, s), '~%d min' % b.minutes(s['secs'])
            if s['secs'] >= 60 else '~%d s' % s['secs']))
        out.append('- **MENU and SELECT:** %s.' % buttons(b, s))
        out.append('')
        if s['say']:
            out += block(b.start_screen(s), s['title'])
            out.append('')
        if s['id'] == 'lvl5':
            out += ['First, inside the step, the go question:', '']
            out += block(b.ask_screen('lvl5 go', b.text(b.pm['BPW_GO_TEXT']),
                                      ['Yes, run it', 'Not now']), s['title'])
            out.append('')
        if s['fn_name'] in ('devbench_pwr_idle', 'devbench_pwr_level',
                            'devbench_pwr_lit'):
            names = re.search(r'%s\(void\).*?\{\s*"(A: [^"]*)",\s*"(B: [^"]*)"\s*\}'
                              % re.escape(s['fn_name']), b.pw, re.S)
            out += ['Each of the 4 phases (the first shown; the screen is '
                    'drawn once a phase and stays still; B phases show "%s"):'
                    % names.group(2), '']
            out += block(b.phase_screen(s['title'], names.group(1)))
            out.append('')
        if s['flags'] & bi.F['BENCH_F_REBOOTS']:
            out += ['After it:', '']
            out += block(b.go_screen('restart', b.text(b.m['RESTART_FMT'] % s['title']),
                                     'MENU_CLOSE', 'GO_CLOSE'), s['title'])
            out.append('')
            out += ['At Go on, if this is still the start that asked for the '
                    'restart (nothing is recorded; the step stays open):', '']
            out += block(b.go_screen('no restart', b.text(
                b.m['NORESTART_FMT'] % s['title']), 'MENU_CLOSE', 'GO_CLOSE'),
                'No restart seen')
            out.append('')
        if s['flags'] & bi.F['BENCH_F_LEAVES']:
            out += ['After it (the session leaves):', '']
            out += block(b.go_screen('left', b.text(b.m['LEFT_FMT'] % s['title']),
                                     'MENU_CLOSE', 'GO_CLOSE'), s['title'])
            out.append('')
        if s['ask']:
            if s['flags'] & bi.F['BENCH_F_GO']:
                when = ''
            elif not s['fn'] or s['flags'] & bi.F['BENCH_F_LEAVES']:
                when = ' (when you come back and pick Go on)'
            else:
                when = ' (asked only if the step ran; a skipped step asks nothing)'
            out += ['The question%s:' % when, '']
            out += block(b.question(s), s['title'])
            out.append('')
        if not s['say'] and not s['ask']:
            out += ['No screen of its own.', '']
    b.check_words()
    out += ['**Fit:** the longest screen has %d rows (one screen shows %d); '
            'every line is at most %d characters.' % (b.rows_max, LIST_ROWS, b.width),
            '', END]
    return '\n'.join(out) + '\n', b.problems


def splice(doc, section):
    if BEGIN in doc:
        i = doc.index(BEGIN)
        j = doc.index(END, i) + len(END) + 1
        return doc[:i] + section + doc[j:]
    anchor = '## The battery rows'
    i = doc.index(anchor)
    return doc[:i] + section + '\n' + doc[i:]


def main(argv):
    section, problems = render()
    doc = open(DOC).read()
    want = splice(doc, section)
    if '--write' in argv:
        with open(DOC, 'w') as f:
            f.write(want)
    elif '--check' in argv:
        bad = False
        for p in problems:
            print('bench_script: does not fit: %s' % p)
            bad = True
        if want != doc:
            print('bench_script: %s differs from the code: run '
                  'python3 scripts/bench_script.py --write' % os.path.relpath(DOC, ROOT))
            bad = True
        if bad:
            return 1
        print('bench_script: the doc matches the code; every screen fits')
        return 0
    else:
        sys.stdout.write(section)
        for p in problems:
            print('does not fit: %s' % p, file=sys.stderr)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
