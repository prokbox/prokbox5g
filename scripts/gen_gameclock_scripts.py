"""Writes tests/ui/ipodui-<game>-long.script: a long session of each SDK game
under `sdk_devclock on` (device-speed game code; docs/design/games.md 5.6).
Deterministic (a fixed LCG), so the scripts are reproducible."""
import sys

GAMES = {"bricks": 0, "chute": 2, "quadrus": 4, "solitaire": 5}

HEAD = """# Long session of {title} under the simulator's device clock (`sdk_devclock
# on`: game code is charged at 30 MHz device speed, docs/design/games.md
# 5.6). Fails on any SDK budget violation or kill; the game's longest step
# is logged at exit. {what}
#   SIM_BUILD=build/sim-ui-mod scripts/shots.sh tests/ui/ipodui-{name}-long.script
# generated by scripts/gen_gameclock_scripts.py
# needs: modules
# needs: music
# golden: skip
# timeout: 900
# reset: mainmenu
# log: sdk devclock {name} step max_us=
# log: sdk devclock {name} entries
# nolog: sdk viol {name}
# nolog: sdk kill {name}

wait 4000
sdk_clear
sdk_devclock on
play_files /Music/Tone%20Collective/Sine%20Studies/01%20Concert%20A.mp3
repeat one
wait 2000
key MENU
wait 1000
wheel -20
wait 600
wheel +2             # Extras
wait 600
key SELECT
wait 1200
wheel +4             # Games
wait 600
key SELECT
wait 1200
wheel +{row}             # {title}
wait 600
key SELECT
wait 1500
"""

TAIL = """hold MENU 900        # leave the game (quadrus: the pause menu)
wait 600
{exit}wait 2000
quit
"""


def lcg(seed):
    s = seed
    while True:
        s = (s * 1103515245 + 12345) & 0x7fffffff
        yield s >> 8


# the suspend/resume entries: a USB session (suspend, resume) and a pause menu
CYCLE = """usb_connect
wait 5000
usb_disconnect
wait 3000
key SELECT           # the pause menu the resume shows: Resume
wait 800
{pause}
wait 800
{resume}
wait 800
"""
PAUSE = {"quadrus": ("hold MENU 900", "key SELECT"),
         "chess": ("hold MENU 900", "key SELECT")}
PAUSE_DEFAULT = ("key MENU", "key SELECT")


def body(name):
    r = lcg(7)
    o = []
    if name == "bricks":
        for i in range(120):
            o.append("wheel %+d 100" % ((next(r) % 21) - 10))
            o.append("wait 250")
            if i % 3 == 0:
                o.append("key SELECT   # launch / serve")
                o.append("wait 700")
            if i % 30 == 29:
                o.append("shot t%d" % i)
    elif name == "chute":
        for i in range(150):
            o.append("wheel %+d 80" % ((next(r) % 5) - 2))
            o.append("wait %d" % (500 + next(r) % 900))
            if i % 6 == 5:
                o.append("key SELECT   # new game when over")
                o.append("wait 300")
            if i % 40 == 39:
                o.append("shot t%d" % i)
    elif name == "quadrus":
        for i in range(260):
            o.append("wheel %+d 80" % ((next(r) % 9) - 4))
            o.append("wait 150")
            k = next(r) % 4
            if k == 0:
                o.append("key SELECT   # turn")
                o.append("wait 450")
            elif k == 1:
                o.append("key SELECT   # double tap: hard drop")
                o.append("wait 100")
                o.append("key SELECT")
                o.append("wait 500")
            else:
                o.append("wait 250")
            if i % 65 == 64:
                o.append("shot t%d" % i)
    elif name == "solitaire":
        for i in range(300):
            o.append("wheel %+d 100" % ((next(r) % 17) - 8))
            o.append("wait 200")
            o.append("key SELECT")
            o.append("wait 350")
            if i % 50 == 49:
                o.append("shot t%d" % i)
    at = len(o) // 3
    pa, re_ = PAUSE.get(name, PAUSE_DEFAULT)
    cyc = CYCLE.format(pause=pa, resume=re_).rstrip("\n")
    o.insert(at * 2, cyc)
    o.insert(at, cyc)
    return "\n".join(o) + "\n"


WHAT = {
    "bricks": "Random paddle sweeps, serves and level play.",
    "chute": "Random rowing for several games (a SELECT tap restarts after Game Over).",
    "quadrus": "Random moves, turns and hard drops through several levels.",
    "solitaire": "Random cursor moves with SELECT: picks, drops and stock draws.",
}
TITLE = {"bricks": "Bricks", "chute": "Chute", "quadrus": "Quadrus",
         "solitaire": "Solitaire"}

for name in (sys.argv[1:] or GAMES):
    with open("tests/ui/ipodui-%s-long.script" % name, "w") as f:
        f.write(HEAD.format(name=name, title=TITLE[name], what=WHAT[name],
                            row=GAMES[name]))
        f.write(body(name))
        f.write(TAIL.format(exit="wheel +3 300\nwait 400\nkey SELECT\n"
                            if name == "quadrus" else ""))
