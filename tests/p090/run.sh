# 0.9.0 P0 contracts (branch p090; docs/changes-from-rockbox.md 3.1-3.5):
#  - the database format bump (SORTKEY_VERSION 3, TAGCACHE_MAGIC, the 0.8.x
#    magic the upgrade's export reads), the unplayable reason (metadata.h
#    enum, tagcache.h flag bits 16-19) and the libglyph stub, in
#    test_contracts.c against the real definitions (sed'ed out of the
#    sources into contracts.h; the expected numbers are literals there);
#  - the english.lang package blocks: genlang accepts the file, the blocks
#    change no generated byte (shell and stock features), and a phrase
#    added inside a block is taken (one more string).
set -u
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
cd "$ROOT"
if [ -z "${HOSTCC:-}" ]; then
    HOSTCC=cc
    for v in 19 18 17 16 15 14; do
        if command -v gcc-$v >/dev/null 2>&1; then HOSTCC=gcc-$v; break; fi
    done
fi
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
fail=0

# --- the C contracts --------------------------------------------------------
H=$TMP/contracts.h
{
    sed -n 's/^\(#define SORTKEY_VERSION [0-9]*\).*/\1/p' apps/ipodui/sortkey.h
    grep -m1 '^#define TAGCACHE_MAGIC  (0x544348a0 + SORTKEY_VERSION)' apps/tagcache.c
    grep -E '^#define (TAGCACHE_UI_UPGRADE_FROM|TAGCACHE_MAGIC_PREV) ' apps/tagcache.c
    awk '/^#define TAGCACHE_UI_UNPLAYABLE_SHIFT/{f=1}
         f{print}
         f&&/^#define TAGCACHE_UI_UNPLAYABLE\(flag\)/{g=1}
         g&&!/\\$/{exit}' apps/tagcache.h
    awk '/^enum unplayable_reason \{/{f=1} f{print} f&&/^\};/{exit}' \
        lib/rbcodec/metadata/metadata.h
} >"$H"
for d in SORTKEY_VERSION 'TAGCACHE_MAGIC ' TAGCACHE_UI_UPGRADE_FROM \
         TAGCACHE_MAGIC_PREV TAGCACHE_UI_UNPLAYABLE_SHIFT \
         TAGCACHE_UI_UNPLAYABLE_MASK TAGCACHE_UI_UNPLAYABLE_FLAG \
         'TAGCACHE_UI_UNPLAYABLE(' UNPLAYABLE_COUNT; do
    grep -qF "$d" "$H" \
        || { echo "FAIL: p090: '$d' not found in the sources"; fail=1; }
done
if [ $fail = 0 ]; then
    if "$HOSTCC" -std=gnu99 -O1 -g -Wall -Wextra -Werror -I"$TMP" \
            -Iapps/ipodui -o "$TMP/t" tests/p090/test_contracts.c \
            2>"$TMP/cc.log"; then
        "$TMP/t" || fail=1
    else
        echo "FAIL: p090: compiling the contracts test"
        cat "$TMP/cc.log"
        fail=1
    fi
fi
# --- package G: the library glyph file and the sparse font form (#235) -------
if "$HOSTCC" -std=gnu99 -O1 -g -Wall -Wextra -Werror -DLIBGLYPH_HOST \
        -Iapps/ipodui -Ifirmware/export -o "$TMP/lg" \
        tests/p090/test_libglyph.c "${LIBGLYPH_C:-apps/ipodui/libglyph.c}" \
        2>"$TMP/lg.log"; then
    "$TMP/lg" || fail=1
else
    echo "FAIL: p090: compiling the libglyph test"
    cat "$TMP/lg.log"
    fail=1
fi

# --- english.lang package blocks ---------------------------------------------
L=apps/lang/english.lang
nb=$(grep -c '^# ----- BEGIN 0\.9\.0 package [A-I]:' $L)
ne=$(grep -c '^# ----- END 0\.9\.0 package [A-I] -----$' $L)
if [ "$nb" != 9 ] || [ "$ne" != 9 ]; then
    echo "FAIL: p090: english.lang has $nb BEGIN and $ne END package lines (want 9 each)"
    fail=1
fi
genl() { # LANGFILE FEATURES OUTDIR -> OUTDIR/lang.h, OUTDIR/lang_core.c
    # the same input and output names every time: genlang writes both
    # into what it generates
    rm -rf "$TMP/g" "$TMP/g_enum.h"; mkdir -p "$3" "$TMP/g"
    cp "$1" "$TMP/english.lang"
    (cd "$TMP" && perl "$ROOT/tools/genlang" -e=english.lang -p=g \
        -t="ipodvideo:$2" english.lang) >"$3/log" 2>&1 \
        && [ -s "$TMP/g/lang.h" ] && mv "$TMP/g/lang.h" "$TMP/g/lang_core.c" "$3/" \
        && mv "$TMP/g_enum.h" "$3/enum.h"
}
# the file without the package blocks' comment lines
awk '/^# ===== 0\.9\.0 package blocks/{skip=1} skip&&/^#/{next} {print}' \
    $L >"$TMP/noblocks.lang"
FS_UI="swcodec:tagcache:tc_ramcache:albumart:ipodui:ipodui_devmode"
FS_STOCK="swcodec:tagcache:tc_ramcache:albumart"
for fs in "$FS_UI" "$FS_STOCK"; do
    genl $L "$fs" "$TMP/a" \
        || { echo "FAIL: p090: genlang refused english.lang ($fs)"; fail=1; }
    genl "$TMP/noblocks.lang" "$fs" "$TMP/b" \
        || { echo "FAIL: p090: genlang (no blocks, $fs)"; fail=1; }
    if cmp -s "$TMP/a/lang.h" "$TMP/b/lang.h" \
            && cmp -s "$TMP/a/enum.h" "$TMP/b/enum.h" \
            && cmp -s "$TMP/a/lang_core.c" "$TMP/b/lang_core.c"; then
        echo "   english.lang blocks: genlang output identical with and without them ($fs)"
    else
        echo "FAIL: p090: the package blocks changed genlang's output ($fs)"
        fail=1
    fi
    rm -rf "$TMP/a" "$TMP/b"
done
# a phrase added inside package F's block is taken
awk '{print}
     /^# ----- BEGIN 0\.9\.0 package F:/{
        print "<phrase>"; print "  id: LANG_IPODUI_P090_BLOCK_PROBE"
        print "  desc: tests/p090 probe"; print "  user: core"
        print "  <source>"; print "    *: none"; print "    ipodui: \"probe\""
        print "  </source>"; print "  <dest>"; print "    *: none"
        print "    ipodui: \"probe\""; print "  </dest>"; print "  <voice>"
        print "    *: none"; print "    ipodui: \"probe\""; print "  </voice>"
        print "</phrase>" }' $L >"$TMP/probe.lang"
genl "$TMP/probe.lang" "$FS_UI" "$TMP/p" \
    || { echo "FAIL: p090: genlang refused a phrase inside a block"; fail=1; }
genl $L "$FS_UI" "$TMP/a"
if grep -q LANG_IPODUI_P090_BLOCK_PROBE "$TMP/p/enum.h" \
        && ! grep -q LANG_IPODUI_P090_BLOCK_PROBE "$TMP/a/enum.h"; then
    echo "   english.lang blocks: a phrase inside package F's block is generated"
else
    echo "FAIL: p090: a phrase inside a package block was not generated"
    fail=1
fi

if [ $fail = 0 ]; then echo "ok   p090 contracts"; else echo "FAIL: p090 contracts"; fi
exit $fail
