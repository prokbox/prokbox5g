/* 0.9.0 P0 contracts (tests/p090/run.sh): the format bump's magic, the
 * unplayable reason's enum and its place in the flag word, and the
 * libglyph header's shape. The numbers are pinned as literals, never taken from the
 * code under test: a change to any of them must change this file too.
 * contracts.h is generated by run.sh from the real sources (sed). */
#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include <stddef.h>
#include "contracts.h"
#include "libglyph.h"

static int fails, checks;
#define CK(cond, ...) do { checks++; if (!(cond)) { fails++; \
        printf("FAIL %s:%d: ", __FILE__, __LINE__); printf(__VA_ARGS__); \
        printf("\n"); } } while (0)

static void format_bump(void)
{
    /* 3.1: one bump for 0.9.0; 0.8.x was 2 */
    CK(SORTKEY_VERSION == 3, "SORTKEY_VERSION %d, want 3", SORTKEY_VERSION);
    CK(TAGCACHE_MAGIC == 0x544348a3u, "TAGCACHE_MAGIC 0x%08x",
       (unsigned)TAGCACHE_MAGIC);
    CK(TAGCACHE_UI_UPGRADE_FROM == 2, "upgrade from %d",
       TAGCACHE_UI_UPGRADE_FROM);
    CK(TAGCACHE_MAGIC_PREV == 0x544348a2u, "TAGCACHE_MAGIC_PREV 0x%08x",
       (unsigned)TAGCACHE_MAGIC_PREV);
    /* the first bytes of every database file, little-endian, as
     * tests/perf/upgrade080.sh and ensure65k.sh read them with od */
    uint32_t m = TAGCACHE_MAGIC, p = TAGCACHE_MAGIC_PREV;
    unsigned char b[4];
    memcpy(b, &m, 4);
    CK(b[0] == 0xa3 && b[1] == 0x48 && b[2] == 0x43 && b[3] == 0x54,
       "magic bytes %02x%02x%02x%02x", b[0], b[1], b[2], b[3]);
    memcpy(b, &p, 4);
    CK(b[0] == 0xa2, "previous magic byte 0 %02x", b[0]);
}

static void unplayable(void)
{
    /* 3.2: append-only values, stored in the database */
    CK(UNPLAYABLE_NONE == 0 && UNPLAYABLE_DRM == 1
       && UNPLAYABLE_PROTECTED == 2 && UNPLAYABLE_CODEC == 3
       && UNPLAYABLE_COUNT == 4, "enum renumbered");
    /* 3.3: bits 16-19 of the flag word */
    CK(TAGCACHE_UI_UNPLAYABLE_SHIFT == 16, "shift %d",
       TAGCACHE_UI_UNPLAYABLE_SHIFT);
    CK((uint32_t)TAGCACHE_UI_UNPLAYABLE_MASK == 0x000f0000u, "mask 0x%08lx",
       (unsigned long)TAGCACHE_UI_UNPLAYABLE_MASK);
    /* round trip through a flag word with every other bit set: the low
     * 16 (all taken), the RAM-only 0x400000 and the rest of the high half */
    static const uint32_t others[] = {
        0x00000000u, 0x0000ffffu, 0x00400000u, 0xfff0ffffu
    };
    for (unsigned o = 0; o < sizeof(others) / sizeof(others[0]); o++)
        for (int r = 0; r < 16; r++)
        {
            int32_t flag = (int32_t)(others[o]
                                     | (uint32_t)TAGCACHE_UI_UNPLAYABLE_FLAG(r));
            CK(TAGCACHE_UI_UNPLAYABLE(flag) == r,
               "reason %d with 0x%08x reads %d", r, (unsigned)others[o],
               TAGCACHE_UI_UNPLAYABLE(flag));
            CK(((uint32_t)flag & ~0x000f0000u) == (others[o] & ~0x000f0000u),
               "reason %d touched other bits", r);
        }
    /* a 0.8.x entry (no reason stored) plays */
    CK(TAGCACHE_UI_UNPLAYABLE(0x0000ffff) == UNPLAYABLE_NONE, "old entry");
}

/* the libglyph contract's fixed shape (its behaviour: test_libglyph.c) */
static void glyph_contract(void)
{
    /* the header: 9 words, every field naturally aligned */
    CK(sizeof(struct libglyph_hdr) == 36, "hdr %zu B",
       sizeof(struct libglyph_hdr));
    CK(offsetof(struct libglyph_hdr, sum) == 32, "sum at %zu",
       offsetof(struct libglyph_hdr, sum));
    CK(LIBGLYPH_MAGIC == 0x4c474c59u && LIBGLYPH_VERSION == 1, "magic");
}

int main(void)
{
    format_bump();
    unplayable();
    glyph_contract();
    printf("   p090 contracts: %d checks, %d failures\n", checks, fails);
    return fails != 0;
}
