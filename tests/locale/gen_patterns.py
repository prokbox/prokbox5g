"""patterns.h for test_locale.c: the date/time patterns, the decimal mark,
the clock default, AM/PM and the month and weekday names, as the four
shell languages ship them (apps/lang/*.lang, the shell build's string:
its ipodui: line, else rtc:, else *:, a leading ~ dropped as genlang
does). Exits 2 if a string is missing: a test that read nothing fails."""
import re, sys

LANGS = ('english', 'deutsch', 'nederlands', 'japanese')
MONTHS = ('JANUARY', 'FEBRUARY', 'MARCH', 'APRIL', 'MAY', 'JUNE', 'JULY',
          'AUGUST', 'SEPTEMBER', 'OCTOBER', 'NOVEMBER', 'DECEMBER')
DAYS = ('SUNDAY', 'MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY',
        'SATURDAY')
SINGLE = (('pat_panel', 'LANG_IPODUI_DATE_PANEL'),
          ('pat_alarm', 'LANG_IPODUI_DATE_ALARM'),
          ('pat_short', 'LANG_IPODUI_DATE_SHORT'),
          ('pat_day', 'LANG_IPODUI_DATE_DAY'),
          ('pat_month', 'LANG_IPODUI_DATE_MONTH'),
          ('pat_caption', 'LANG_IPODUI_DATE_CAPTION'),
          ('pat_time12', 'LANG_IPODUI_TIME_12H'),
          ('pat_time24', 'LANG_IPODUI_TIME_24H'),
          ('lang_dec', 'LANG_IPODUI_DECIMAL_SEP'),
          ('lang_clock', 'LANG_IPODUI_CLOCK_DEFAULT'),
          ('lang_am', 'LANG_IPODUI_AM'),
          ('lang_pm', 'LANG_IPODUI_PM'))


def dests(path):
    out = {}
    text = open(path, encoding='utf-8').read()
    for ph in text.split('<phrase>')[1:]:
        m = re.search(r'^\s*id:\s*(\S+)', ph, re.M)
        d = re.search(r'<dest>(.*?)</dest>', ph, re.S)
        if not m or not d:
            continue
        t = {}
        for line in d.group(1).splitlines():
            lm = re.match(r'\s*([^:]+):\s*"(.*)"\s*$', line)
            if lm:
                t[lm.group(1).strip()] = lm.group(2)
        for k in ('ipodui', 'rtc', '*'):
            if k in t:
                out[m.group(1)] = re.sub(r'^~+', '', t[k])
                break
    return out


def c_str(s):
    return '"' + ''.join(c if 32 <= ord(c) < 127 and c not in '"\\?'
                         else ''.join('\\x%02x' % b for b in c.encode())
                         + '""' for c in s) + '"'


def main():
    root = sys.argv[1]
    tabs = [dests('%s/apps/lang/%s.lang' % (root, l)) for l in LANGS]
    out = ['/* generated by tests/locale/gen_patterns.py */']
    missing = []

    def get(i, pid):
        v = tabs[i].get(pid)
        if v is None:
            missing.append('%s %s' % (LANGS[i], pid))
            return ''
        return v
    for name, pid in SINGLE:
        out.append('static const char *const %s[4] = { %s };' % (
            name, ', '.join(c_str(get(i, pid)) for i in range(4))))
    for name, ids in (('lang_month', ['LANG_MONTH_' + m for m in MONTHS]),
                      ('lang_wday', ['LANG_WEEKDAY_' + d for d in DAYS]),
                      ('lang_wday_full', ['LANG_IPODUI_' + d for d in DAYS])):
        rows = ['{ %s }' % ', '.join(c_str(get(i, p)) for p in ids)
                for i in range(4)]
        out.append('static const char *const %s[4][%d] = {\n    %s };'
                   % (name, len(ids), ',\n    '.join(rows)))
    if missing:
        print('FAIL: missing strings: ' + ', '.join(missing))
        return 2
    sys.stdout.write('\n'.join(out) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
