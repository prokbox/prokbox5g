# Polyphase FIR prototype for the fractional-ratio path of
# lib/rbcodec/dsp/resample.c (#271, docs/design/resample-plan.md section 9).
#
#   tests/resample/fir_design.py           print lib/rbcodec/dsp/resample_fir_coefs.h
#   tests/resample/fir_design.py --specs   print the measured response
#   tests/resample/fir_design.py --check H compare header H with a fresh
#                                          design (+/-2 LSB: the least-squares
#                                          solve may differ in its last bits
#                                          between BLAS builds); exit 1 if not
#
# The fractional stage always runs on a signal that a half-band has already
# limited to 0.2268 of its rate (x2 by hb_t44 first), so the FIR only has to
# keep the passband flat to 0.2268 and kill the images that sit within
# 0.2268 of each multiple of its input rate. Everything between is a
# "don't care" band (the half-band left only its -91 dB residue there).
# That lets a 10-tap-per-phase filter reach about 100 dB where a plain
# lowpass with the same edges needs 12 or more.
#
# Weighted least squares over the continuous prototype h(t), |t| < T/2 input
# samples, sampled at P points per sample (P + 1 rows of T taps, so that
# linear interpolation between neighbouring rows never runs off the end).
# Row j, tap i holds h(j/P + T/2 - 1 - i): tap 0 is the oldest input sample.
# Q31; the whole table is scaled once so that the rows' mean sum is 1.0
# (unity DC gain). Rows are not normalised one by one: their sums differ by
# about 5e-5, and forcing each to 1.0 would modulate the gain with the phase
# (spurs near -85 dB).
import sys

import numpy as np

T = 10          # taps per phase
P = 64          # phases per input sample (linear interpolation between)
PASS = 0.2268   # passband edge, fraction of the FIR's input rate
STOP = 1.0 - PASS
W_PASS, W_STOP, W_DONTCARE = 1e4, 1e8, 1e-3


def design():
    n_half = T * P // 2
    n = np.arange(0, n_half + 1) / P
    f = np.linspace(0, P / 2, 60000)
    c = np.cos(2 * np.pi * np.outer(f, n))
    c[:, 1:] *= 2
    c /= P
    want = (f <= PASS).astype(float)
    fr = np.abs(f - np.round(f))
    w = np.full_like(f, W_DONTCARE)
    w[f <= PASS] = W_PASS
    w[(f >= STOP) & (fr <= PASS)] = W_STOP
    sw = np.sqrt(w)
    half = np.linalg.lstsq(c * sw[:, None], want * sw, rcond=None)[0]
    return np.concatenate([half[:0:-1], half])     # t = -T/2 .. T/2


def table(h):
    """(P + 1) x T rows of Q31, mean row sum 2^31."""
    mid = T * P // 2                 # index of t = 0 in h
    fl = [[h[mid + j + (T // 2 - 1 - i) * P] for i in range(T)]
          for j in range(P + 1)]
    g = 1.0 / np.mean([sum(r) for r in fl[:P]])
    return [[int(round(v * g * 2147483648.0)) for v in r] for r in fl]


def response(rows):
    """Frequency response of the quantised table read as one long filter
    sampled at P per input sample (row j, tap i at t = j/P + T/2 - 1 - i)."""
    taps = {}
    for j in range(P):
        for i in range(T):
            taps[(T // 2 - 1 - i) * P + j] = rows[j][i] / 2147483648.0
    k = np.array(sorted(taps))
    v = np.array([taps[x] for x in k])
    f = np.linspace(0, 8, 64001)
    hf = (v[None, :] * np.exp(-2j * np.pi * np.outer(f, k / P))).sum(1) / P
    mag = np.abs(hf)
    fr = np.abs(f - np.round(f))
    pb = f <= PASS
    sb = (f >= STOP) & (fr <= PASS)
    ripple = np.max(np.abs(20 * np.log10(mag[pb])))
    stop = 20 * np.log10(np.max(mag[sb]))
    peak = 20 * np.log10(np.max(mag))
    return ripple, stop, peak


def header(rows):
    ripple, stop, peak = response(rows)
    out = []
    out.append("/* Generated by tests/resample/fir_design.py; do not edit by hand")
    out.append(" * (tests/resample/run.sh checks it against a fresh design).")
    out.append(" * %d taps x %d phases (+1 for interpolation), Q31, mean row sum 1.0." % (T, P))
    out.append(" * Passband 0..%.4f fs within +/-%.4f dB; images within %.4f fs of"
               % (PASS, ripple, PASS))
    out.append(" * each multiple of fs %.1f dB down; peak gain %+.3f dB. */" % (stop, peak))
    out.append("#ifndef _DSP_RESAMPLE_FIR_COEFS_H")
    out.append("#define _DSP_RESAMPLE_FIR_COEFS_H")
    out.append("")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("#define RS_FIR_TAPS   %d" % T)
    out.append("#define RS_FIR_PHASES %d" % P)
    out.append("")
    out.append("/* Global: resample_fir_arm.S reads it. Include this header only in")
    out.append(" * resample_fir.c. */")
    out.append("const int32_t rs_fir_proto[RS_FIR_PHASES + 1][RS_FIR_TAPS] =")
    out.append("{")
    for r in rows:
        out.append("    { %s }," % ", ".join("%d" % v for v in r))
    out.append("};")
    out.append("")
    out.append("#endif /* _DSP_RESAMPLE_FIR_COEFS_H */")
    return out


def parse(path):
    rows = []
    for line in open(path):
        s = line.strip()
        if s.startswith("{ ") and s.endswith(" },"):
            rows.append([int(v) for v in s[2:-3].split(",")])
    return rows


def main():
    rows = table(design())
    if "--specs" in sys.argv:
        print("ripple %.5f dB, image rejection %.1f dB, peak %+.4f dB" % response(rows))
        return
    if "--check" in sys.argv:
        old = parse(sys.argv[sys.argv.index("--check") + 1])
        ok = (len(old) == len(rows) and
              all(len(a) == len(b) and max(abs(x - y) for x, y in zip(a, b)) <= 2
                  for a, b in zip(old, rows)))
        print("ok" if ok else "differs")
        sys.exit(0 if ok else 1)
    print("\n".join(header(rows)))


if __name__ == "__main__":
    main()
