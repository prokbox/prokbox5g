# Host test of the Fit-3 step 0 counters (firmware/export/devstats.h).
# Compiler: the newest Homebrew gcc-NN, else cc; override with HOSTCC=...
set -u
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
cd "$ROOT"
T=tests/devstats

if [ -z "${HOSTCC:-}" ]; then
    HOSTCC=cc
    for v in 19 18 17 16 15 14; do
        if command -v gcc-$v >/dev/null 2>&1; then HOSTCC=gcc-$v; break; fi
    done
fi

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
# the header beside the stubs, so its own "config.h" is the stub's
cp firmware/export/devstats.h $T/stub/config.h $T/stub/thread.h "$TMP/"
# shellcheck disable=SC2086
if ! "$HOSTCC" -std=gnu99 -O1 -g -Wall -Wextra -Werror ${EXTRA_CFLAGS:-} \
        -I"$TMP" -o "$TMP/test_fit3" \
        "$T/test_fit3.c" 2>"$TMP/cc.log"; then
    echo "FAIL: compiling test_fit3 ($HOSTCC)"
    cat "$TMP/cc.log"
    exit 1
fi
if "$TMP/test_fit3"; then
    echo "ok   Fit-3 counters (devstats.h: adds, max kept, deltas across a wrap)"
else
    echo "FAIL: Fit-3 counters"
    exit 1
fi
