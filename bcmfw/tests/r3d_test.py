"""The 3D render test's renderer (bcmfw/r3d, docs/research/bcm2722/render3d.md)
in vc2sim: each scene built, frames rendered at fixed points of its camera
path, each frame's checksum against the golden table the device test
compares with (firmware/target/arm/ipod/video/bcm-devtest-r3d.h), the
instruction counts turned into frame-time estimates, and the frames
written as PNGs (out/r3d/) to look at.

Usage: bcmfw/tests/r3d_test.py [--png] [--write] [--scenes 0,1,2,3]
  --write  regenerate the golden header from this run
  --video FPS  also render each scene's 10 s loop at FPS in the
               simulator into out/r3d/r3d-preview.mp4 (slow: about 3 s a
               frame; bcmfw/r3d/host's build does the same in seconds)
"""
import os
import struct
import sys
import time
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.dirname(HERE)
ROOT = os.path.dirname(FW)
R3D = os.path.join(FW, 'r3d')
sys.path.insert(0, os.path.join(ROOT, 'tools', 'bcmre'))
import vc2cc as C     # noqa: E402
import vc2sim as S    # noqa: E402

CFLAGS = ['-std=gnu99', '-Wall', '-Wextra', '-Werror', '-Wno-unused-parameter',
          '-fno-tree-loop-distribute-patterns']
W, H = 320, 240
# the renderer's memory in the simulator (the image uses config.h's)
MEM = 0x3F0000
STATS = 0x3F0100
TEX, CLUT, VERTS, TRIS = 0x400000, 0x410000, 0x420000, 0x430000
XVERTS, OT, PRIMS, FB = 0x440000, 0x458000, 0x460000, 0x500000
# the frames each scene is checked at (ms on its path); the device test
# renders the same two before it runs the scene live
CHECK_MS = (0, 5000)
GOLDEN = os.path.join(ROOT, 'firmware', 'target', 'arm', 'ipod', 'video',
                      'bcm-devtest-r3d.h')
SCALAR_CYC = 1.03               # cycles per scalar instruction (S7 bench)


def build():
    return C.build([os.path.join(R3D, 'r3d.c'), os.path.join(R3D, 'r3d_scene.c')],
                   '-O2', extra=CFLAGS + ['-I' + R3D, '-DR3D_SIM'], libs=C.DEFAULT_LIBS,
                   no_float=True, conservative=True)


def call(sim, name, *args, steps=400_000_000):
    return sim.call(name, *args, check_abi=True, max_steps=steps, regs={15: 0, 22: 0})


def rgb(v):
    return ((v >> 11) * 255 // 31, ((v >> 5) & 63) * 255 // 63, (v & 31) * 255 // 31)


def png_write(path, pix):
    raw = bytearray()
    for y in range(H):
        raw.append(0)
        for x in range(W):
            raw += bytes(rgb(pix[y * W + x]))

    def chunk(t, d):
        return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d))
    with open(path, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', W, H, 8, 2, 0, 0, 0))
                + chunk(b'IDAT', zlib.compress(bytes(raw), 6)) + chunk(b'IEND', b''))


def fnv(words):
    h = 0x811C9DC5
    for w in words:
        h = ((h ^ w) * 0x01000193) & 0xFFFFFFFF
    return h


def golden():
    """{(scene, ms): crc} from the header, or {}."""
    out = {}
    if not os.path.exists(GOLDEN):
        return out
    for line in open(GOLDEN):
        line = line.strip()
        if line.startswith('{') and 'R3D_GOLDEN' not in line:
            f = [x.strip() for x in line.strip('{},').split(',')]
            if len(f) == 3:
                out[(int(f[0]), int(f[1]))] = int(f[2], 16)
    return out


def write_golden(rows):
    from prokbox_header import convert  # noqa: E402
    body = ['#ifndef BCM_DEVTEST_R3D_H', '#define BCM_DEVTEST_R3D_H', '',
            '/* Generated by bcmfw/tests/r3d_test.py --write: each scene\'s',
            ' * checksum (r3d_crc) at two points of its camera path, as vc2sim',
            ' * renders them.  The device test compares the chip\'s with these. */',
            '', 'struct bcmdt_r3d_golden { uint8_t scene; uint16_t ms; uint32_t crc; };',
            '', 'static const struct bcmdt_r3d_golden bcmdt_r3d_golden[] =', '{']
    for (sc, ms), crc in sorted(rows.items()):
        body.append('    { %d, %d, 0x%08x },' % (sc, ms, crc))
    body += ['};', '', '#endif /* BCM_DEVTEST_R3D_H */', '']
    text, _ = convert('\n'.join(body), '.h')
    with open(GOLDEN, 'w') as f:
        f.write(text)


def video(sim, fps, scenes, path):
    """Each scene's 10 s loop as the chip would show it at fps, 2x."""
    import subprocess
    os.makedirs(os.path.dirname(path), exist_ok=True)
    ff = subprocess.Popen(['ffmpeg', '-v', 'error', '-y', '-f', 'rawvideo', '-pix_fmt', 'rgb24',
                           '-s', '%dx%d' % (W, H), '-r', str(fps), '-i', '-',
                           '-vf', 'scale=%d:%d:flags=neighbor' % (2 * W, 2 * H),
                           '-pix_fmt', 'yuv420p', '-c:v', 'libx264', '-crf', '18', path],
                          stdin=subprocess.PIPE)
    lut = [rgb(v) for v in range(65536)]
    for sc in scenes:
        call(sim, 'r3d_scene', sc)
        for k in range(10 * fps):
            call(sim, 'r3d_render', k * 1000 // fps, FB, STATS)
            words = struct.unpack('<%dI' % (W * H // 2), sim.mem.read(FB, W * H * 2))
            ff.stdin.write(b''.join(bytes(lut[w & 0xFFFF]) + bytes(lut[w >> 16]) for w in words))
            if k % fps == 0:
                print('video: scene %d, %d s' % (sc, k // fps), flush=True)
    ff.stdin.close()
    ff.wait()
    print('wrote %s' % os.path.relpath(path, ROOT))


def host_check(rows):
    """The renderer built for the Mac (bcmfw/r3d/host) must give the
    simulator's checksums: then its previews are what the chip draws."""
    import subprocess
    exe = os.path.join(ROOT, 'build', 'r3d-host', 'r3d_host')
    os.makedirs(os.path.dirname(exe), exist_ok=True)
    src = [os.path.join(R3D, 'host', 'r3d_host.c'), os.path.join(R3D, 'r3d.c'),
           os.path.join(R3D, 'r3d_scene.c')]
    r = subprocess.run(['cc', '-O2', '-std=gnu99', '-fwrapv', '-I' + R3D, '-o', exe] + src,
                       capture_output=True, text=True)
    if r.returncode:
        print('FAIL host build:\n' + r.stderr)
        return 1
    bad = 0
    for line in subprocess.run([exe, 'crc'], capture_output=True, text=True).stdout.split('\n'):
        if not line:
            continue
        sc, ms, crc = line.split()[:3]
        want = rows.get((int(sc), int(ms)))
        if want is not None and want != int(crc, 16):
            print('FAIL host build: scene %s at %s ms %s, simulator %08x' % (sc, ms, crc, want))
            bad += 1
    print('host build: %s' % ('matches the simulator' if not bad else '%d differ' % bad))
    return bad


def main(argv):
    import argparse
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--png', action='store_true')
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--scenes', default='0,1,2,3,4')
    ap.add_argument('--extra-ms', default='', help='more frames for the PNGs, e.g. 2500,7500')
    ap.add_argument('--video', type=int, default=0, metavar='FPS')
    ap.add_argument('--no-host', action='store_true', help='skip the Mac build check')
    a = ap.parse_args(argv)
    if not os.path.exists(C.GCC):
        print('skip: vc4-elf-gcc not found (%s)' % C.GCC)
        return 0
    t0 = time.time()
    prog = build()
    sim = S.Sim()
    C.load_into_sim(prog, sim)
    sim.mem.write(MEM, struct.pack('<7I', TEX, CLUT, VERTS, TRIS, XVERTS, OT, PRIMS))
    call(sim, 'r3d_init', MEM)
    gold = golden()
    rows, bad, cases = {}, 0, 0
    outdir = os.path.join(ROOT, 'out', 'r3d')
    if a.png:
        os.makedirs(outdir, exist_ok=True)
    extra = [int(x) for x in a.extra_ms.split(',') if x]
    for sc in [int(x) for x in a.scenes.split(',')]:
        ntris = call(sim, 'r3d_scene', sc)
        nverts = sim.mem.r32(prog.symbols['r3d_nverts'])
        for ms in list(CHECK_MS) + extra:
            s0 = sim.steps
            call(sim, 'r3d_render', ms, FB, STATS)
            n = sim.steps - s0
            st = struct.unpack('<9I', sim.mem.read(STATS, 36))
            words = struct.unpack('<%dI' % (W * H // 2), sim.mem.read(FB, W * H * 2))
            crc = fnv(words)
            chip = call(sim, 'r3d_crc', FB)
            cyc = n * SCALAR_CYC
            line = ('scene %d at %5d ms: %4d tris, %4d drawn, %4d culled (chunks %d in, %d out), '
                    '%3d clipped, %6d px; %5.2f M instr: %5.1f ms at 150 MHz, %6.1f at 27; '
                    'crc %08x' % (sc, ms, ntris, st[1], st[2], st[5], st[6], st[3], st[4],
                                  n / 1e6, cyc / 150e3, cyc / 27e3, crc))
            if chip != crc:
                line += ' FAIL r3d_crc %08x' % chip
                bad += 1
            if ms in CHECK_MS:
                cases += 1
                rows[(sc, ms)] = crc
                want = gold.get((sc, ms))
                if want is not None and want != crc and not a.write:
                    line += ' FAIL golden %08x' % want
                    bad += 1
            print(line, flush=True)
            if a.png:
                png_write(os.path.join(outdir, 'scene%d-%05d.png' % (sc, ms)),
                          [p for w in words for p in (w & 0xFFFF, w >> 16)])
    if a.scenes == '0,1,2,3,4' and not a.no_host:
        bad += host_check(rows)
    if a.video:
        video(sim, a.video, [int(x) for x in a.scenes.split(',')],
              os.path.join(ROOT, 'out', 'r3d', 'r3d-preview.mp4'))
    if a.write:
        sys.path.insert(0, os.path.join(ROOT, 'scripts'))
        write_golden(rows)
        print('wrote %s' % os.path.relpath(GOLDEN, ROOT))
    elif len(gold) != len(rows) and a.scenes == '0,1,2,3,4':
        print('FAIL golden table has %d rows, this run %d (run --write)' % (len(gold), len(rows)))
        bad += 1
    print('%d cases, %d failed (%.0f s)' % (cases, bad, time.time() - t0))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
