# Vector checks: a model of the documented semantics (isa.md).

def s16(v):
    v &= 0xffff
    return v - 0x10000 if v & 0x8000 else v


class VRF:
    """64 x 64 bytes.  H16(y, x) lane i: bytes (y, x + i) low, (y, x + i + 16) high."""
    def __init__(self):
        self.b = bytearray(64 * 64)

    def get16(self, y, x=0):
        return [s16(self.b[y * 64 + x + i] | self.b[y * 64 + x + i + 16] << 8)
                for i in range(16)]

    def get8(self, y, x=0):
        return [self.b[y * 64 + x + i] for i in range(16)]       # unsigned

    def put16(self, y, vals, lanes=range(16), x=0):
        for i in lanes:
            v = vals[i] & 0xffff
            self.b[y * 64 + x + i] = v & 0xff
            self.b[y * 64 + x + i + 16] = v >> 8

    def put8(self, y, vals, lanes=range(16), x=0):
        for i in lanes:
            self.b[y * 64 + x + i] = vals[i] & 0xff

    def load16(self, y, halves):            # vld16: 32 bytes, halfword i -> lane i
        self.put16(y, halves)

    def store16(self, y):                   # vst16: lane i -> halfword i
        return [v & 0xffff for v in self.get16(y)]

    def load8(self, y, data):               # vld8: 16 bytes -> row y, columns 0-15
        for i in range(16):
            self.b[y * 64 + i] = data[i]


def sat8(v):
    return 0 if v < 0 else 255 if v > 255 else v


def mulhr(a, b):
    """vmulhr/vmulhrs: B unsigned, ties away from zero (device session 6,
    MHRN: -16 * 2048 gave -1; isa.md 'v_mulhr_round')."""
    p = a * (b & 0xffff)
    return -((-p + 0x8000) >> 16) if p < 0 else (p + 0x8000) >> 16


def a16x(x):
    """The x an H16 A operand's +r x adds (vc2sim HYP v_a16_reg_x 'near32',
    silicon ASHF/ASHG and ASHX, quirks #30): rounded to the nearest 32"""
    return ((x + 16) & ~31) & 63


def sat32(v):
    return max(-0x80000000, min(0x7FFFFFFF, v))


class Acc:
    """One lane's accumulator as silicon keeps it (X15S, REPA; vc2sim HYP
    v_acc_sat 'sat32'): 32 bits, saturating at every add"""
    def __init__(self):
        self.t = 0

    def hi(self, v):            # 'acc': v at bit 16; the result is the high half
        self.t = sat32(self.t + (v << 16))
        return self.t >> 16

    def lo(self, v):            # 'x15': v (already extended) at bit 0; the low half
        self.t = sat32(self.t + v)
        return self.t & 0xFFFF


def _yx(r):
    """A check's row key: y, or (y, x) for a row outside x block 0."""
    return r if isinstance(r, tuple) else (r, 0)


class VCase:
    """rows: (VRF row, 16 halfwords) loaded with vld16 from the input block;
    outs: rows stored with vst16 to out, 32 bytes each; scal: at most one
    (register, value), stored with a scalar st at out[0] (the VRF read
    back through the scalar-result unit, no vector store); the rest of
    that 32-byte slot keeps the fill, and the rows follow it."""
    def __init__(self, tag, form, rows, test, outs, model, pre=(), post=(), regs=(),
                 note='', scal=(), raw=False, info=False):
        assert len(tag) == 4
        self.tag, self.form, self.rows, self.test = tag, form, rows, list(test)
        self.outs, self.model = outs, model
        self.pre, self.post, self.regs, self.note = list(pre), list(post), list(regs), note
        self.scal = list(scal)
        self.raw = raw      # store with the old load-style fields (control)
        self.info = info    # informational: not in BR_VEC_ALL, may use t5 blocks
        assert len(self.scal) <= 1

    @property
    def name(self):
        return 'bench_vc_' + self.tag.lower()

    def nwords(self):
        """Words of out[] the check compares"""
        return 8 * len(self.outs) + 8 * len(self.scal)

    def block(self):
        """Input block: the loaded rows, 32 bytes each, in order."""
        return [h & 0xffff for y, hs in self.rows for h in hs]

    def expected(self):
        v = VRF()
        for r, hs in self.rows:
            y, x = _yx(r)
            v.put16(y, hs, x=x)
        self.model(v, dict(self.rows))
        out = []
        for _, val in self.scal:            # the scalar slot: value, then fill
            out += [val & 0xffff, (val >> 16) & 0xffff] + [FILL & 0xffff] * 14
        return out + [h & 0xffff for r in self.outs for h in v.get16(*_yx(r))]

    def asm(self):
        out = ['/* %s: %s */' % (self.tag, self.note or self.form),
               '    .global %s' % self.name, '%s:' % self.name]
        out += ['    mov r%d, #%d' % (r, v) for r, v in self.regs]
        for j, (r, _) in enumerate(self.rows):
            out.append('    ' + V.mem('vld16', H16(*_yx(r)), 0, off=32 * j))
        out += ['    ' + l for l in self.pre]
        out += ['    ' + l for l in self.test]
        out += ['    ' + l for l in self.post]
        slot = 32 * len(self.scal)
        for m, r in enumerate(self.outs):
            # dev5: every row is stored directly with the silicon layout
            # (vpu_asm.st16_fields; session 5).  COP8 keeps the old
            # load-style encoding as its control (raw).
            y, x = _yx(r)
            out.append('    %s    /* row %d%s -> +%d */' % (
                V.mem('vst16', H16(y, x), 1, off=slot + 32 * m, unproven=self.info,
                      raw=self.raw), y, ', x %d' % x if x else '', slot + 32 * m))
        for reg, _ in self.scal:
            out.append('    st r%d, (r1)' % reg)
        out += ['    rts', '']
        return out


