class Kernel:
    def __init__(self, tag, body, ops, rows=0, setup=(), pre=(), counter='r0',
                 labels=(), note='', extra=0):
        assert len(tag) == 4
        self.tag, self.body, self.ops, self.rows = tag, list(body), ops, rows
        self.setup, self.pre, self.counter = list(setup), list(pre), counter
        self.labels = set(labels)   # body lines that are labels (not executed)
        self.note = note
        self.extra = extra          # executed per iteration outside the body

    @property
    def name(self):
        return 'bench_k_' + self.tag.strip().lower()

    @property
    def executed_body(self):
        return [l for l in self.body if l not in self.labels and not l.endswith(':')
                and not l.startswith('.')]

    @property
    def per_iter(self):
        return len(self.pre) + len(self.executed_body) + self.extra + 1

    def asm(self):
        out = ['/* %s: %s */' % (self.tag, self.note),
               '    .global %s' % self.name, '%s:' % self.name,
               '    push r6-r9, lr']
        out += ['    ' + l for l in self.setup]
        if self.counter != 'r0':
            out.append('    mov %s, r0' % self.counter)
        out += ['    mov r8, #0x%08x' % TIMER_CLO, '    ld r9, (r8)',
                '%s_loop:' % self.name]
        out += ['    ' + l for l in self.pre]
        for l in self.body:
            out.append(l if l.endswith(':') else '    ' + l)
        out += ['    addcmpbne %s, #-1, #0, %s_loop' % (self.counter, self.name),
                '    ld r0, (r8)', '    sub r0, r9', '    pop r6-r9, pc', '']
        return out


def tag4(s):
    return (s + '    ')[:4]


