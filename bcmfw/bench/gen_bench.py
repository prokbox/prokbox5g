# ---- HWLD: the halfword loads (quirks.md #16 and #33) -----------------------
# The input block holds the halfwords 0x8001, 0xFFFF, 0xFFFF, 0x8001 at
# +0, +2, +4, +6 (offsets 0 and 2 mod 4, each value at both).  Each form
# loads all four into r3 and stores the 32-bit register to out[0..3], so
# a record's got words read straight against both readings: 0x00008001 /
# 0x0000ffff zero-extended, 0xffff8001 / 0xffffffff sign-extended.  The
# loads are raw halfwords (the encoding pinned, whatever the assembler
# calls it); every one occurs in Apple's code (vc2forms).  Informational:
# a reading other than the model's names itself in readlog, it can't
# fail stage 4.
HWLD_HALVES = (0x8001, 0xFFFF, 0xFFFF, 0x8001)
# tag, form, the model's reading (True: sign-extends), evidence
HWLD_FORMS = (
    ('HL16', 'ldh rd, (rs) (16-bit, 0xBAsd)', False,
     '[silicon] zero-extends: px[0] of jref_f16w, 2026-10-25'),
    ('HS16', 'ldsh rd, (rs) (16-bit, 0xBEsd)', True, '[silicon] sign-extends: S16, S17'),
    ('H28O', '0x28sd off|1 (32-bit, offset)', False,
     '[silicon] zero-extends: S17, and every 0x28 load of the images since'),
    ('H29O', '0x29sd off|1 (32-bit, offset)', True,
     '[silicon] sign-extends: the 2026-10-25 COMMIT sums'),
    ('H48H', '48-bit 2f0d op 2 ("ldh"), rs + off', False, '[hypothesis] Apple\'s name'),
    ('H48S', '48-bit 2f8d op 6 ("ldsh"), rs + off', True, '[hypothesis] Apple\'s name'),
    ('HSP0', '2d4d off|1 (sp-relative, width class 0)', False,
     '[hypothesis] as 0x28/o1 (the same class field)'),
    ('HSP1', '2d5d off|1 (sp-relative, width class 1)', True,
     '[hypothesis] as 0x29/o1 (the same class field)'),
)


def hwld_words(tag, off):
    """The load of the halfword at r0 + off (r2 + 0 for the 16-bit forms,
    sp + off for the sp-relative ones) into r3, as raw halfwords"""
    if tag == 'HL16':
        return [0xBA23]
    if tag == 'HS16':
        return [0xBE23]
    if tag in ('H28O', 'H29O'):
        return [(0x2800 if tag == 'H28O' else 0x2900) | 0x03, off | 1]
    if tag in ('H48H', 'H48S'):
        b7 = tag == 'H48S'
        return [0x2f00 | b7 << 7 | ((off >> 1) & 1) << 6 | (off & 1 if b7 else 0) << 5 | 3,
                (off & ~3 & 0xffff) | 2, 0 << 11 | ((off >> 16) & 0x7ff)]
    return [(0x2d40 if tag == 'HSP0' else 0x2d50) | 3, off | 1]


class HCase:
    """A halfword-load check (HWLD): the VCase interface, scalar code"""
    info = True
    rows = ()
    outs = ()
    scal = ()
    test = pre = post = regs = ()   # scalar code: no vector forms

    def __init__(self, tag, form, signed, evidence):
        self.tag, self.form, self.signed, self.note = tag, form, signed, \
            'informational, HWLD: %s; the model: %s (%s)' % (
                form, 'sign-extends' if signed else 'zero-extends', evidence)

    @property
    def name(self):
        return 'bench_vc_' + self.tag.lower()

    def nwords(self):
        return 4

    def block(self):
        return list(HWLD_HALVES)

    def expected(self):
        out = []
        for h in HWLD_HALVES:
            v = (h | 0xFFFF0000) if self.signed and h & 0x8000 else h
            out += [v & 0xffff, v >> 16]
        return out

    def asm(self):
        out = ['/* %s: %s */' % (self.tag, self.note),
               '    .global %s' % self.name, '%s:' % self.name]
        sp = self.tag.startswith('HSP')
        if sp:
            out += ['    add sp, #-8', '    ld r4, (r0)', '    st r4, (sp+0)',
                    '    ld r4, (r0+4)', '    st r4, (sp+4)']
        for j, off in enumerate((0, 2, 4, 6)):
            ws = hwld_words(self.tag, off)
            if len(ws) == 1:
                out.append('    mov r2, r0' if off == 0 else '    add r2, r0, #%d' % off)
            out.append('    .hword %s' % ', '.join('0x%04x' % w for w in ws))
            out.append('    st r3, (r1+%d)' % (4 * j) if j else '    st r3, (r1)')
        if sp:
            out.append('    add sp, #8')
        out += ['    rts', '']
        return out


def hwld_cases():
    return [HCase(*f) for f in HWLD_FORMS]


def putv_case(xr):
    """PUTV (P19, jdec's put and fill; gen_jdec.py jv_put, jv_fill;
    jpeg-spike.md section 16): a V8 D at +r2 = 8 * 64 + 17 (row 8, column
    17: a +r y that is not a multiple of 16) from an H8 A at +r5 = 8
    (row 48, x 8), so column 17 of rows 8-15 gets row 48's bytes 8-15 (rows
    16-23 too, not stored); then the masked fill, vbitplanes #0x5555 setf
    and vmov D8 at +r3 = 16 (x only) from r4 = 0xA5, REP 16 stepping a row,
    ifnz: rows 0-15, columns 16 + even lanes = 0xA5 (column 17 kept).  Rows
    0-15 stored."""
    rows = [(y, [xr.randint(-32768, 32767) for _ in range(16)]) for y in range(16)]
    src = [xr.randint(-32768, 32767) for _ in range(16)]

    def m_putv(v, r):
        # silicon (sitting 2): the V8 D's +r y 8 aligns down to 16 (vc2sim
        # v_vd_reg_y 'align16', quirks #39): lanes 0-15 into rows 0-15
        for i in range(16):
            v.b[i * 64 + 17] = v.b[48 * 64 + 8 + i]
        for y in range(16):
            for i in range(0, 16, 2):
                v.b[y * 64 + 16 + i] = 0xA5
    return VCase('PUTV', 'vmov D8 A8 Breg ifnz rep, D at +r (x 16); after vadd D8 A8 '
                 'Bimm, D a V8 column at +r (y 8, x 17), A at +r',
                 rows + [(48, src)],
                 [V.alu('vadd', V.V8(0, 0, reg=2), H8(48, 0, reg=5), 0),
                  V.bitplanes(0x5555),
                  V.alu('vmov', H8(0, 0, step=True, reg=3), None, Reg(4), rep=16,
                        pred='ifnz')],
                 list(range(16)), m_putv,
                 regs=[(2, 8 * 64 + 17), (5, 8), (3, 16), (4, 0xA5)], info=True,
                 note='informational: jdec\'s put (a V8 D at +r, y 8 and x 17, from '
                      'an H8 A at +r x 8) and fill (vmov D8 at +r x 16 ifnz rep16 '
                      'after vbitplanes #0x5555)')


def barv_case(xr):
    """BARV (P19, the visualizer's bars; gen_viz.py jv_bars16,
    visualizer.md section 5): one 16 x 16 block through every vector form
    jv_bars16 runs, in its order, on its VRF layout.  X rows 0-15 (the
    block), rows 48-52 x 0 the first bar rows, first and last cap rows, f
    and the rows' indices (rr = 32).  The gradient's three channels (vmul
    by a register, vasr #8, vadd of a register, vmul #2048 and #32, the
    sums) into row 53; its broadcast and the indices' down the V16 columns
    of rows 16-31 x 32 (GC) and 32-47 x 0 (RI); the background on the
    mask's lanes (vbitplanes r5 setf, vmov D16 r3 rep16 ifnz); the lanes
    whose bar covers the group (vsub Ddiscard B16 r2 setf, vadd D16 #0
    rep16 ifn); the bar select (vsub with an unstepped B row, vasr #15,
    vsub, vmul by a stepped B, vadd); the cap select (vrsub with an
    unstepped B row, vmin, vasr #15, vrsub and vadd of r4).  Rows 0-15
    stored."""
    X = [[xr.randint(-32768, 32767) for _ in range(16)] for _ in range(16)]
    rr = 32
    bst = [0x4000, 32, 33, 40, 47, 48, 31, 0, 0x4000, 35, 44, 32, 46, 47, 50, 39]
    cs = [0x4000, 36, 36, 0x4000, 0, 30, 47, 33, 0x4000, 40, 40, 31, 0x4000, 45, 32, 36]
    ce = [xr.randint(-32768, 32767), 37, 37, 9, 32, 34, 50, 33, 77, 41, 43, 32, 5, 47, 40, 36]
    f = [0, 255, 1, 128, 17, 254, 64, 200, 3, 99, 127, 129, 240, 15, 31, 77]
    ri = [rr + k for k in range(16)]
    bot, top = 0x9A5C, 0x2DE3
    ch = ((bot >> 11, (top >> 11) - (bot >> 11), 2048),
          (bot >> 5 & 63, (top >> 5 & 63) - (bot >> 5 & 63), 32),
          (bot & 31, (top & 31) - (bot & 31), 0))
    bg, cap, mask = 0x1234, 0xFEDC, 0x7FF8
    rows = [(y, X[y]) for y in range(16)] + [(48, bst), (49, cs), (50, ce), (51, f), (52, ri)]
    test = []
    for k, (c0, dc, scale) in enumerate(ch):
        d = H16(53 + k, 0)
        test += ['mov r4, #%d' % dc, V.alu('vmul', d, H16(51, 0), Reg(4)),
                 V.alu('vasr', d, d, 8), 'mov r4, #%d' % c0, V.alu('vadd', d, d, Reg(4))]
        if scale:
            test.append(V.alu('vmul', d, d, scale))
    st = lambda o: o.stepped()      # noqa: E731
    Xb, T, M, GC, RI = H16(0, 0), H16(0, 32), H16(16, 0), H16(16, 32), H16(32, 0)
    test += [V.alu('vadd', H16(53, 0), H16(53, 0), H16(54, 0)),
             V.alu('vadd', H16(53, 0), H16(53, 0), H16(55, 0)),
             V.alu('vadd', V16(16, 32, True), H16(53, 0), 0, rep=16),
             V.alu('vadd', V16(32, 0, True), H16(52, 0), 0, rep=16),
             V.bitplanes(Reg(5)),
             V.alu('vmov', st(Xb), None, Reg(3), rep=16, pred='ifnz'),
             V.alu('vsub', DISCARD, H16(48, 0), Reg(2), setf=True),
             V.alu('vadd', st(Xb), st(GC), 0, rep=16, pred='ifn'),
             V.alu('vsub', st(M), st(RI), H16(48, 0), rep=16),
             V.alu('vasr', st(M), st(M), 15, rep=16),
             V.alu('vsub', st(T), st(GC), st(Xb), rep=16),
             V.alu('vmul', st(T), st(T), st(M), rep=16),
             V.alu('vadd', st(Xb), st(GC), st(T), rep=16),
             'mov r4, #%d' % cap,
             V.alu('vsub', st(M), st(RI), H16(49, 0), rep=16),
             V.alu('vrsub', st(T), st(RI), H16(50, 0), rep=16),
             V.alu('vmin', st(M), st(M), st(T), rep=16),
             V.alu('vasr', st(M), st(M), 15, rep=16),
             V.alu('vrsub', st(T), st(Xb), Reg(4), rep=16),
             V.alu('vmul', st(T), st(T), st(M), rep=16),
             V.alu('vadd', st(Xb), st(T), Reg(4), rep=16)]

    def m_barv(v, r):
        col = [0] * 16
        for c0, dc, scale in ch:
            col = [(a + (c0 + ((dc * fk) >> 8)) * (scale or 1)) & 0xFFFF
                   for a, fk in zip(col, f)]
        x = [[w & 0xFFFF for w in row] for row in X]
        for k in range(16):
            for l in range(16):
                if mask >> l & 1:
                    x[k][l] = bg
                if bst[l] - (rr + 1) < 0:
                    x[k][l] = col[k]
                m = (ri[k] - bst[l]) >> 15
                x[k][l] = (col[k] + (col[k] - x[k][l]) * m) & 0xFFFF
                m = min(s16(ri[k] - cs[l]), s16(ce[l] - ri[k])) >> 15
                x[k][l] = (cap + (cap - x[k][l]) * m) & 0xFFFF
        for k in range(16):
            v.put16(k, x[k])
    return VCase('BARV', 'vadd D16 A16 Breg, rep too, vmul D16 A16 Bimm, vadd V16 D from '
                 'H16 A Bimm rep (the broadcast), vmov D16 Breg ifnz rep, vsub Ddiscard '
                 'Breg setf, vadd D16 Bimm ifn rep, vmul/vrsub/vmin D16 A16 B16 rep, '
                 'vrsub D16 Breg rep: jv_bars16\'s block',
                 rows, test, list(range(16)), m_barv,
                 regs=[(2, rr + 1), (3, bg), (4, cap), (5, mask)], info=True,
                 note='informational: the visualizer\'s vector bars (jv_bars16): one '
                      'block through its every form, in order')


# REPA (P19, jv_idct8x4's products; jpeg-spike.md §13): REP 8 with 'acc'
# adds every repetition into the one accumulator.  Lanes 0-7 of A's rows
# (rows 16-23, through +r4 = 1024) and of B's columns (V16 column j of rows
# 32-47 is H16 lane j of those rows); readlog.py copies them.  Lane 0:
# eight 2^30 products (the sum wraps at 32 bits); lane 1: eight low halves
# that carry 7 into the high half; lanes 2-7: mixed signs.
REPA_SEED = 514                 # vmov #514 clra acc: pass 2's seed (high half)
REPA_A = ((-32768, 255, -1, 32767, -300, 12345, 7, -20000),
          (-32768, 255, 2, -32768, 300, -12345, -7, 20000),
          (-32768, 255, -3, 1, -1280, 100, 4000, -1),
          (-32768, 255, 4, -1, 1280, -100, -4000, 1),
          (-32768, 255, -5, 32767, -320, 2047, 30000, -29999),
          (-32768, 255, 6, 32767, 320, -2048, -30000, 29999),
          (-32768, 255, -7, -32768, 11, 1, 32767, 5),
          (-32768, 255, 8, -32768, -11, -1, -32768, -5))   # [j][lane]
REPA_B = ((-32768, 255, 32767, 2, 100, -3, 9, 16384),
          (-32768, 255, -32768, -2, 300, -3, -9, 16384),
          (-32768, 255, 1000, 32767, -500, 11585, 25080, -1),
          (-32768, 255, -1000, 32767, 700, -11585, 25080, -1),
          (-32768, 255, 12, -32768, 900, 6270, -15137, 7),
          (-32768, 255, -12, 1, -1100, 15137, 6270, 7),
          (-32768, 255, 4096, -1, 1300, -4433, 32767, -32768),
          (-32768, 255, -4096, 2, -1500, 4433, -32768, 32767))   # [j][lane]


def repa_readings(a, b, seed=REPA_SEED):
    """The accumulator's halves (TL, TH) per lane after 'vmov #seed clra
    acc', 'vmul x15 rep8', 'vmulhd acc rep8' (A row j, B column j), under
    the three readings: a[j][i], b[j][i] -> {reading: (TL, TH)}, 16-bit
    signed lists.  saturates: every repetition adds into a 32-bit
    accumulator that saturates (silicon 2026-10-25, vc2sim v_acc_sat
    'sat32'); accumulates: every repetition adds, the sum wrapping mod 2^32
    (the model before);
    last: only the last repetition adds, onto the accumulator as it was;
    restart: each repetition starts from a cleared accumulator, so only
    the last product is left (the seed and the low half lost)."""
    def s16(v):
        return ((v & 0xFFFF) ^ 0x8000) - 0x8000
    out = {k: ([], []) for k in ('saturates', 'accumulates', 'last', 'restart')}
    for i in range(len(a[0])):
        p = [a[j][i] * b[j][i] for j in range(8)]
        acc = Acc()
        acc.hi(seed)
        for j in range(8):
            tl = acc.lo(p[j] & 0xFFFF)
        for j in range(8):
            th = acc.hi(p[j] >> 16)
        out['saturates'][0].append(s16(tl))
        out['saturates'][1].append(s16(th))
        for k, js in (('accumulates', range(8)), ('last', [7])):
            t = (seed << 16) + sum(x & 0xFFFF for x in (p[j] for j in js))
            tl = t & 0xFFFF
            t += sum((p[j] >> 16) << 16 for j in js)
            out[k][0].append(s16(tl))
            out[k][1].append(s16(t >> 16))
        out['restart'][0].append(s16(p[7]))
        out['restart'][1].append(s16(p[7] >> 16))
    return out


def repa_case(xr):
    """REPA: jv_idct8x4's eight products of one output, its exact form:
    vmov Ddiscard #514 clra acc (pass 2's seed), vmul TL A B rep8 x15, then
    vmulhd TH A B rep8 acc, A = H16 row 16 + j (+r4, stepping a row), B =
    V16 column j of rows 32-47 (stepping a column).  Row 49 (TH) first,
    then row 48 (TL)."""
    def r16(edges=()):
        e = list(edges)
        return e + [xr.randint(-32768, 32767) for _ in range(16 - len(e))]
    arows = [r16(REPA_A[j]) for j in range(8)]
    # B: row 32 + i holds lane i's eight constants in lanes 0-7
    bcols = [r16(REPA_B[j]) for j in range(8)]
    brows = [[bcols[j][i] for j in range(8)] + [xr.randint(-32768, 32767) for _ in range(8)]
             for i in range(16)]
    ra = repa_readings(REPA_A, REPA_B)
    for k in range(8):           # lanes 0-7 tell the wrapping readings apart
        th = [ra[m][1][k] for m in ('accumulates', 'last', 'restart')]
        assert len(set(th)) == 3, (k, th)

    def m_repa(v, r):
        a = [v.get16(16 + j) for j in range(8)]
        b = [[v.get16(32 + i)[j] for i in range(16)] for j in range(8)]
        tl, th = repa_readings(a, b)['saturates']
        v.put16(49, th)
        v.put16(48, tl)
    a, b = H16(0, 0, step=True, reg=4), V16(32, 0, step=True)
    return VCase('REPA', 'vmul D16 A16 B16 x15 rep, then vmulhd acc, REP 8 with A and B stepping',
                 [(16 + j, arows[j]) for j in range(8)] +
                 [(32 + i, brows[i]) for i in range(16)] + [(48, r16()), (49, r16())],
                 [V.alu('vmov', DISCARD, None, REPA_SEED, clra=True, acc=True),
                  V.alu('vmul', H16(48, 0), a, b, rep=8, x15=True),
                  V.alu('vmulhd', H16(49, 0), a, b, rep=8, acc=True)],
                 [49, 48], m_repa, regs=[(4, 1024)], info=True,
                 note='informational: REP 8 accumulates across repetitions, saturating '
                      'at 32 bits (silicon): #514 << 16 '
                      'plus eight products (A row 16 + j at +r4, B the V16 column j of '
                      'rows 32-47), vmul x15 rep8 then vmulhd acc rep8 (jv_idct8x4): '
                      'row 49 = the high half, row 48 = the low half')


def x15_text48(text):
    """A 48-bit ALU instruction from its text, checked by a round trip
    and decoded by vc2sim's model (vpu_asm has no 48-bit ALU builder)."""
    ins = V._decode(text)
    V.VP.VInsn(ins)
    return text


