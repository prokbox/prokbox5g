def kernels():
    return scalar_kernels() + vector_kernels()


def generate():
    K, C = kernels(), vcases()
    tags = [k.tag for k in K] + [c.tag for c in C]
    assert len(tags) == len(set(tags)), 'duplicate tags'
    assert len(C) <= 64                     # bench.h: two pass words
    return gen_s(K, C), gen_c(K, C)


def main(argv):
    s, c = generate()
    s = prokbox_header.convert(s, '.S')[0]
    c = prokbox_header.convert(c, '.c')[0]
    if '--check' in argv:
        bad = [p for p, t in ((OUT_S, s), (OUT_C, c))
               if not os.path.exists(p) or open(p).read() != t]
        for p in bad:
            print('gen_bench: %s is stale' % os.path.relpath(p))
        return 1 if bad else 0
    for p, t in ((OUT_S, s), (OUT_C, c)):
        with open(p, 'w') as f:
            f.write(t)
    print('wrote %s, %s' % (os.path.relpath(OUT_S), os.path.relpath(OUT_C)))
    return 0


