                    V.alu('vmulhd', DISCARD, H16(0, 0), -320, acc=True),
                    V.alu('vmul', DISCARD, H16(1, 0), 1280, x15=True),
                    V.alu('vmulhd', DISCARD, H16(1, 0), 1280, acc=True),
