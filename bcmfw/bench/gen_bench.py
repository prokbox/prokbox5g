# Store-locating check (isa.md "Vector stores on silicon").  Session 5
# (dev4) answered where a 48-bit vst16 with a nonzero hw2 goes: the byte a
# load reads as D is the address offset in 32-byte units, and the source
# row sits in the load's offset field.  dev5 checks that layout: each
# source below is loaded with tagged halfwords, then stored with the
# silicon encoding (vpu_asm.st16_fields) to the middle of bench_vbuf,
# which bench.c filled with FILL and scans for what changed.  The last
# record is the old load-style encoding 'vst16 d08' as a control: under
# the layout it stores row 0 at +256 bytes.
# Halfword i of source (y, x) = tag << 8 | i, tag = 0x80 | y (0x40 | y
# for x = 32; dev4's tags were 0xC0 + y): any word found names its row,
# block and lanes.
SLOC_SRCS = ((0, 0), (8, 0), (16, 0), (33, 0), (0, 32))
# dev9 (informational, offload.md): one vst16 REP 16 with a 64-byte stride
# from rows 0-15, the store the display path and the drift kernel use;
# its rows come after the sources in the input block
SLOC_REP = 'rep16'
SLOC_REP_STRIDE = 64
SLOC_RECS = [(y, x, False) for y, x in SLOC_SRCS] + [(8, 0, True), (0, 0, SLOC_REP)]
SLOC_TARGET = 4096              # bytes into bench_vbuf


def sloc_tag(y, x):
    return (0x40 if x == 32 else 0x80) | y


def sloc_half(y, x, i):
    return sloc_tag(y, x) << 8 | i


def sloc_code(y, x, raw):
    """The record's source word (bench.h BS_ROW low half): 0x8000 the
    load-style control, 0x4000 the REP 16 store (dev9)."""
    return y | x << 8 | (0x4000 if raw == SLOC_REP else 0x8000 if raw else 0)


def sloc_block():
    """vld16 input: the sources, 32 bytes each, in SLOC_SRCS order, then
    rows 0-15 for the REP 16 record."""
    return [sloc_half(y, x, i) for y, x in SLOC_SRCS for i in range(16)] + \
        [sloc_half(y, 0, i) for y in range(16) for i in range(16)]


def sloc_expect(y, x, raw):
    """(byte offset from the target, source) where the record's store lands
    under the silicon layout."""
    if raw == SLOC_REP:         # row 0 at the target; rows 1-15 follow
        return 0, (0, 0)
    if raw:                     # d08 = +8 x 32 bytes, from row 0
        return 8 * 32, (0, 0)
    return 0, (y, x)


def sloc_asm():
    out = ['/* Store-locating check: load the tagged sources, store one (dev5) */']
    for k, (y, x, raw) in enumerate(SLOC_RECS):
        out += ['    .global bench_sloc_%d' % k, 'bench_sloc_%d:' % k]
        if raw == SLOC_REP:
            n = len(SLOC_SRCS)
            for j in range(16):
                out.append('    ' + V.mem('vld16', H16(j, 0), 0, off=32 * (n + j)))
            out.append('    mov r2, #%d' % SLOC_REP_STRIDE)
            out.append('    %s    /* REP 16, stride %d: rows 0-15 */' % (
                V.mem('vst16', H16(0, 0), 1, stride=2, rep=16), SLOC_REP_STRIDE))
            out += ['    rts', '']
            continue
        for j, (ly, lx) in enumerate(SLOC_SRCS):
            out.append('    ' + V.mem('vld16', H16(ly, lx), 0, off=32 * j))
        out.append('    %s    /* %s */' % (
            V.mem('vst16', H16(y, x), 1, unproven=True, raw=raw),
            'old load-style d08' if raw else 'row %d, x %d -> +0' % (y, x)))
        out += ['    rts', '']
    return out


