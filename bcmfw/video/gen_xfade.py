"""Generate the drift offload kernels (xfade_kernels.S): one step of the
shell's panel cross-fade (apps/ipodui/preview.c xfade_rect()) on the
VideoCore II vector unit, bit for bit (docs/research/bcm2722/offload.md).
Stage 5b's mode B image (BCMFW_DRIFT, bcmfw/video/drift.c) runs them.

The panel is kept on the BCM as three 16-bit planes (R5, G6, B5 per
lane): the state (what the panel shows now) and the incoming picture.
Per field, as xfade_rect does in its packed form:

    f' = (d * (32 - w) + s * w + 16) >> 5        w = (weight + 4) >> 3, >= 1

The new fields go back to the state planes and, packed, to the RGB565
framebuffer.  Only forms the device checked (bench, sessions 4-7):
vld16 with REP and a stride, vmul D16 A16 Breg rep (MULR), vadd D16 A16
B16 and #imm (ALUX, ADIR), vmulhr D16 A16 #imm on non-negative A (MHR4),
single vst16 stores of block-0 rows under the silicon layout (COPY,
COP8).  The REP 16 form of vst16 (session 8's informational store check)
is the second kernel, xfade_blk_rep; drift.c picks one at build time
(BCMFW_DRIFT_REP_STORE, 0 = the single stores).

  xfade_blk(out, state, src, w) / xfade_blk_rep(...)
      one 16x16 block: out rows OUT_PITCH bytes apart (the LCD
      framebuffer), state and source rows PLANE_PITCH apart, each plane
      PLANE bytes after the last.  All addresses multiples of 32;
      w = 1..32.

Usage: bcmfw/video/gen_xfade.py [--check]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'h264'))
from vpu_asm import H8, H16, Reg, alu, mem      # noqa: E402

OUT_S = os.path.join(HERE, 'xfade_kernels.S')

