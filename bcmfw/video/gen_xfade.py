# The layout drift.c uses (config.h BCMFW_DRIFT_*): a 160-pixel panel
OUT_PITCH = 640                 # the LCD framebuffer: 320 RGB565 pixels
PLANE_PITCH = 320               # 160 lanes of 16 bits
PLANE = PLANE_PITCH * 240       # one 160 x 240 plane

# VRF (H16 rows, 16 each):
#   F    rows 0-15 x 0: the new field, then the packed pixels (stores
#        only from block 0 under the silicon layout)
#   D    rows 16-31 x 0: the state field;  S rows 16-31 x 32: the source's
#   ACC  rows 32-47 x 0;  TMP rows 32-47 x 32
#   P    rows 48-63 x 0: the packed sum;  Q rows 48-63 x 32: G << 5
F, D, S = H16(0, 0), H16(16, 0), H16(16, 32)
ACC, TMP = H16(32, 0), H16(32, 32)
P, Q = H16(48, 0), H16(48, 32)


def st(o):
    return o.stepped()


def store_block(out, base, pitch, rep):
    """F rows 0-15 to r(base) + row * pitch: one REP 16 store with the
    stride in r5, or 16 single stores (offsets up to 8160: the output's
    second half from a moved base)."""
    if rep:
        out.append('mov r5, #%d' % pitch)
        out.append(mem('vst16', st(F), base, 0, 5, 16))
        return
    per = min(16, 8160 // pitch + 1)
    for r in range(16):
        if r and r % per == 0:
            out.append('mov r7, #%d' % (per * pitch))
            out.append('add r%d, r7' % base)
        out.append(mem('vst16', H16(r, 0), base, (r % per) * pitch))


def xfade_blk(rep=False):
    out = []

    def s(text):
        out.append(text)

    def v(op, d, a, b):
        out.append(alu(op, st(d), st(a), b if not hasattr(b, 'kind') else st(b), rep=16))

    # r0 out, r1 state, r2 src, r3 w (1..32); r4 plane pitch, r5 store
    # stride, r6 32 - w, r7 constants
    s('push r6-r7')
    s('mov r6, #32')
    s('sub r6, r3')                             # 32 - w
    s('mov r4, #%d' % PLANE_PITCH)
    for c in range(3):
        s(mem('vld16', D, 1, 0, 4, 16))
        s(mem('vld16', S, 2, 0, 4, 16))
        v('vmul', ACC, S, Reg(3))               # s * w
        v('vmul', TMP, D, Reg(6))               # d * (32 - w)
        v('vadd', ACC, ACC, TMP)
        # (acc + 16) >> 5 = (acc * 2048 + 0x8000) >> 16; 0 <= acc <= 63 * 32
        v('vmulhr', F, ACC, 2048)
        if rep:
            store_block(out, 1, PLANE_PITCH, True)      # the new state
        else:
            s('mov r5, r1')
            store_block(out, 5, PLANE_PITCH, False)
        # immediates, not r7: a scalar B operand in r7 reads as 0 on
        # silicon (device session 22, vc2vpu v_sreg7)
        if c == 0:
            v('vmul', P, F, 2048)               # R << 11
        elif c == 1:
            v('vmul', Q, F, 32)                 # G << 5
            v('vadd', P, P, Q)
        else:
            v('vadd', P, P, F)                  # + B
        if c < 2:
            s('mov r7, #%d' % PLANE)
            s('add r1, r7')
            s('add r2, r7')
    v('vadd', F, P, 0)
    store_block(out, 0, OUT_PITCH, rep)
    s('pop r6-r7')
    s('rts')
    return out


STG_PITCH = 320                 # the staged window: 160 pixels a row


def half_blk():
    """The 8b half step (preview.c half_window/avg_rows, AVG2): one 16x16
    block of the panel (r0, rows OUT_PITCH apart: the window on screen)
    averaged with the staged next window (r1, rows STG_PITCH apart), per
    RGB565 channel, floor ((a + b) >> 1, which is AVG2 per channel), back
    into r0.  A 16-bit row loaded by vld16 holds its pixels' low bytes in
    H8 columns 0-15 and high bytes in 16-31 (vc2vpu's VRF layout, which
    the display path also uses); the channels come out of the bytes with
    device-checked forms only: vlsr D8 A8 #imm (LSR8), vmul D16 A8 Breg
    (MU8R, WRAP), vadd D16 A16 B8 (AD68), vadd D16 A16 B16 (ALUX),
    vmul D16 A16 Breg (MULR), vmulhr D16 A16 #imm on 0..126 (MHR4):
    vmulhr #32767 = floor(v / 2) there.
      lo = G2-0 B4-0, hi = R4-0 G5-3:  R = hi >> 3;  G = (hi - R * 8) * 8
      + (lo >> 5);  B = lo - (lo >> 5) * 32"""
    out = []

    def s(text):
        out.append(text)

    def v(op, d, a, b):
        out.append(alu(op, st(d), st(a), b if not hasattr(b, 'kind') else st(b), rep=16))

    A, B = H16(16, 0), H16(16, 32)              # the two windows
    loA, hiA, loB, hiB = H8(16, 0), H8(16, 16), H8(16, 32), H8(16, 48)
    RA, RB, GLA, GLB = H8(32, 0), H8(32, 16), H8(32, 32), H8(32, 48)
    T0, T1 = H16(48, 0), H16(48, 32)            # 16-bit temporaries
    GB = H16(0, 32)                             # beside F (bytes 32-63)
    # r0 panel, r1 staged; r4 strides, r5 output base, r6/r7 constants
    s('push r6-r7')
    s('mov r4, #%d' % OUT_PITCH)
    s(mem('vld16', A, 0, 0, 4, 16))
    s('mov r4, #%d' % STG_PITCH)
    s(mem('vld16', B, 1, 0, 4, 16))
    v('vlsr', RA, hiA, 3)                       # R
    v('vlsr', RB, hiB, 3)
    v('vlsr', GLA, loA, 5)                      # G's low 3 bits
    v('vlsr', GLB, loB, 5)
    s('mov r6, #-8')
    v('vmul', T1, RA, Reg(6))                   # G_A = (hi - R*8) * 8 + lo >> 5
    v('vadd', T1, T1, hiA)
    v('vmul', T1, T1, 8)                        # not r7 (v_sreg7)
    v('vadd', T1, T1, GLA)
    v('vmul', GB, RB, Reg(6))                   # G_B, the same
    v('vadd', GB, GB, hiB)
    v('vmul', GB, GB, 8)
    v('vadd', GB, GB, GLB)
    v('vadd', T1, T1, GB)                       # G_A + G_B
    v('vmulhr', T1, T1, 32767)                  # floor / 2
    s('mov r6, #1')
    v('vmul', T0, RA, Reg(6))                   # R_A + R_B
    v('vadd', T0, T0, RB)
    v('vmulhr', T0, T0, 32767)
    s('mov r6, #2048')
    v('vmul', F, T0, Reg(6))                    # R << 11
    s('mov r6, #32')
    v('vmul', T1, T1, Reg(6))                   # + G << 5
    v('vadd', F, F, T1)
    s('mov r6, #-32')
    v('vmul', GB, GLA, Reg(6))                  # B_A = lo - (lo >> 5) * 32
    v('vadd', GB, GB, loA)
    v('vmul', T0, GLB, Reg(6))                  # B_B
    v('vadd', T0, T0, loB)
    v('vadd', GB, GB, T0)
    v('vmulhr', GB, GB, 32767)
    v('vadd', F, F, GB)                         # + B
    s('mov r5, r0')
    store_block(out, 5, OUT_PITCH, False)
    s('pop r6-r7')
    s('rts')
    return out


def copy_blk():
    """The staged window into the panel, one 16x16 block (r0 panel, rows
    OUT_PITCH apart; r1 staged, STG_PITCH apart): vld16 REP 16 and single
    block-0 stores (COPY, COP8)."""
    out = ['mov r4, #%d' % STG_PITCH, mem('vld16', st(F), 1, 0, 4, 16)]
    out.append('push r6-r7')
    out.append('mov r5, r0')
    store_block(out, 5, OUT_PITCH, False)
    out += ['pop r6-r7', 'rts']
    return out


def gen_s():
    lines = [HEADER, '    .syntax vc2', '    .text', '',
             ]
    for name, rep in (('xfade_blk', False), ('xfade_blk_rep', True)):
        lines += ['/* one 16x16 cross-fade step, %s stores (offload.md) */'
                  % ('REP 16' if rep else 'single-row'),
                  '    .global ' + name, name + ':']
        lines += ['    ' + l for l in xfade_blk(rep)] + ['']
    for name, fn, what in (('half_blk', half_blk, 'the 8b half step (AVG2)'),
                           ('copy_blk', copy_blk, 'the staged window copied')):
        lines += ['/* one 16x16 block: %s (offload.md) */' % what,
                  '    .global ' + name, name + ':']
        lines += ['    ' + l for l in fn()] + ['']
    return '\n'.join(lines)


def main(argv):
    text = prokbox_header.convert(gen_s(), '.S')[0]
    if '--check' in argv:
        if not os.path.exists(OUT_S) or open(OUT_S).read() != text:
            print('gen_xfade: stale: xfade_kernels.S')
            return 1
        print('gen_xfade: up to date')
        return 0
    with open(OUT_S, 'w') as f:
        f.write(text)
    print('gen_xfade: 4 kernels, %d, %d, %d and %d instructions' % (
        len(xfade_blk()), len(xfade_blk(True)), len(half_blk()), len(copy_blk())))
    return 0


