class K:
    def __init__(self, name, comment):
        self.name, self.comment, self.lines = name, comment, []

    def s(self, text):
        self.lines.append(text)

    def v(self, op, d, a, b, rep=16):
        self.lines.append(alu(op, d, a, b, rep=rep))

    def text(self):
        out = ['', '/* %s */' % self.comment, '    .global %s' % self.name,
               '%s:' % self.name]
        out += ['    ' + l for l in self.lines]
        return out


def st(o):
    """The operand stepping one row per REP."""
    return o.stepped()


# ---------------------------------------------------------------------------
# disp_yuv_tile.  VRF layout (rows y, byte columns x):
#   Y8   H8 rows 0-15 x 0: even picture rows (0-7 left 16 pixels, 8-15
#        right 16); rows 16-31 x 0: odd rows, same split
#   YT   H16 rows 0-31 x 32: (Y * 4769) >> 8 of the same rows
#   RAWU H8 rows 0-7 at x 0 and x 16 (the same U row twice), RAWV rows
#        8-15, before the luma: as H16 rows their bytes interleave to
#        u0 u0 u1 u1 ..., stored to disp_scratch (one store from d00:
#        U at +0, V at +256) and loaded back as 8-bit rows: the
#        horizontally repeated chroma, CU (H8 rows 32-47 x 0) and CV
#        (x 16), split left/right as Y8
#   RC   H16 rows 48-63 x 0, GC rows 32-47 x 32, BC rows 48-63 x 32: the
#        chroma terms of R, G, B with the constants and the +8
#   TMP  H16 rows 0-15 x 0 (over Y8, once YT is made): G's second term
#   T    H16 rows 32-47 x 0 (over CU/CV): YT + term, per channel
#   R8, G8, B8: H8 rows 0-15 x 0, x 16, rows 16-31 x 0 (then >> 3/2/3)
#   Z8   H8 row 31 x 16: zero, the clip's saturating add
#   P    H16 rows 32-47 x 0: R5 << 11 + G6 << 5; Q H16 rows 0-15 x 0:
#        G6 << 5, then the RGB565 rows (P + B), eight at a time in rows
#        0-7: a 48-bit store only from d00 (isa.md, "Vector stores on
#        silicon")

Y8E, Y8O = H8(0, 0), H8(16, 0)
YTE, YTO = H16(0, 32), H16(16, 32)
CU, CV = H8(32, 0), H8(32, 16)
Z8 = H8(31, 16)             # zero, for the clip: x 16-31 of rows 16-31 is free
RC, GC, BC = H16(48, 0), H16(32, 32), H16(48, 32)
TMP = H16(0, 0)
T = H16(32, 0)
R8, G8, B8 = H8(0, 0), H8(0, 16), H8(16, 0)
P, Q = H16(32, 0), H16(0, 0)


def yuv_tile():
    k = K('disp_yuv_tile', 'one 32x16 tile, YUV 4:2:0 -> RGB565 (dispref.py)')
    # r0 dst, r1 dpitch, r2 y, r3 ystride, r4 u, r5 v
    # (memory-op strides are r0-r6 only)
    k.s('push r6-r7')
    k.s('mov r6, r3')
    k.s('lsr r6, #1')                          # chroma stride
    # chroma rows, each twice (x 0 and x 16), any alignment
    for reg, row in ((4, 0), (5, 8)):
        for x in (0, 16):
            k.s(mem('vldp8', H8(row, x), reg, 0, 6, 8))
            k.s(mem('vldq8', H8(row, x), reg, 0, 6, 8))
    # interleave through memory: 32-byte rows u0 u0 u1 u1 ... u15 u15.
    # The base is r6 (free once the chroma is in): a base field of 7 reads
    # as no register on silicon (sessions 13-14, vc2vpu v_mem_base7)
    k.s('mov r6, #disp_scratch')
    k.s('mov r4, #32')
    k.s(mem('vst16', H16(0, 0), 6, 0, 4, 16))   # rows 8-15 land at +256
    # luma: even rows (stride 2 * ystride), then odd rows
    k.s('mov r5, r3')
    k.s('lsl r5, #1')
    for row, base_add in ((0, False), (16, True)):
        if base_add:
            k.s('add r2, r3')
        for half in (0, 1):
            d = H8(row + 8 * half, 0)
            k.s(mem('vldp8', d, 2, 16 * half, 5, 8))
            k.s(mem('vldq8', d, 2, 16 * half, 5, 8))
    # the repeated chroma back: left halves rows 32-39, right 40-47
    for half in (0, 1):
        k.s(mem('vld8', H8(32 + 8 * half, 0), 6, 16 * half, 4, 8))
        k.s(mem('vld8', H8(32 + 8 * half, 16), 6, 256 + 16 * half, 4, 8))
    # luma term
    k.v('vmulm', st(YTE), st(Y8E), R.KY)
    k.v('vmulm', st(YTO), st(Y8O), R.KY)
    # chroma terms (16 rows: 8 chroma rows, left and right)
    k.v('vmulm', st(RC), st(CV), R.KRV)
    k.v('vadd', st(RC), st(RC), R.CR)
    k.v('vmulm', st(GC), st(CU), -R.KGU)
    k.v('vmulm', st(TMP), st(CV), -R.KGV)
    k.v('vadd', st(GC), st(GC), st(TMP))
    k.v('vadd', st(GC), st(GC), R.CG)
    k.v('vmulm', st(BC), st(CU), R.KBU)
    k.v('vadd', st(BC), st(BC), R.CB)
    # a zero 8-bit row for the clip, from r3 (free once the luma is in).
    # Not r7: a scalar B operand naming r7 reads 0 on silicon (sessions
    # 22 and 24, data-paths.md D4), right here only because it is 0
    k.s('mov r3, #0')
    k.v('vmov', Z8, None, _reg(3), rep=1)
    # the two blocks (even rows, odd rows): both use chroma rows 0-15
    k.s('mov r6, #2048')
    k.s('mov r5, r1')
    k.s('lsl r5, #1')                          # 2 * dpitch
    for yt, odd in ((YTE, False), (YTO, True)):
        for out8, term in ((R8, RC), (G8, GC), (B8, BC)):
            k.v('vadd', st(T), st(yt), st(term))
            # clip((q + 8) >> 4): (q * 4096 + 0x8000) >> 16 in 16 bits,
            # then a saturating add to zero.  On silicon vmulhrs into 8
            # bits keeps the low 8 bits (device session 5, isa.md MHRN);
            # vadds D8 A8 B16 clamps (ADSN, device-verified)
            k.v('vmulhr', st(T), st(T), 0x1000)
            k.v('vadds', st(out8), Z8, st(T))
        k.v('vlsr', st(R8), st(R8), 3)
        k.v('vlsr', st(G8), st(G8), 2)
        k.v('vlsr', st(B8), st(B8), 3)
        k.v('vmul', st(P), st(R8), _reg(6))       # R5 << 11
        k.v('vmul', st(Q), st(G8), _reg(4))       # G6 << 5 (in place over G8)
        k.v('vadd', st(P), st(P), st(Q))
        if odd:
            k.s('add r0, r1')
        # + B into rows 0-7 (Q, consumed), left half then right half
        for half in (0, 1):
            k.v('vadd', st(Q), st(H16(32 + 8 * half, 0)), st(H8(16 + 8 * half, 0)),
                rep=8)
            k.s(mem('vst16', Q, 0, 32 * half, 5, 8))
    k.s('pop r6-r7')
    k.s('rts')
    return k


def _reg(n):
    from vpu_asm import Reg
    return Reg(n)


# ---------------------------------------------------------------------------
# disp_box2_16 / disp_box2_8: rows of 32 bytes loaded as 16-bit vectors
# deinterleave themselves (bytes 2i at x, 2i + 1 at x + 16), so the four
# samples of each output are lane-aligned.
#   even input rows: H16 rows 0..n-1 x 0; odd: rows 16..16+n-1 x 0
#   sums: H16 rows 0.. x 32 (even pair), 16.. x 32 (odd pair)
#   out:  H8 rows 0.. x 0 (over the even rows, consumed): a 48-bit store
#         only from d00

def box2(n):
    k = K('disp_box2_%d' % n, '2:1 box, 32x%d -> 16x%d (dispref.box2)' % (2 * n, n))
    # r0 dst, r1 dstride, r2 src, r3 sstride
    k.s('mov r4, r3')
    k.s('lsl r4, #1')
    k.s(mem('vld16', H16(0, 0), 2, 0, 4, n))
    k.s('add r2, r3')
    k.s(mem('vld16', H16(16, 0), 2, 0, 4, n))
    k.v('vadd', st(H16(0, 32)), st(H8(0, 0)), st(H8(0, 16)), rep=n)
    k.v('vadd', st(H16(16, 32)), st(H8(16, 0)), st(H8(16, 16)), rep=n)
    k.v('vadd', st(H16(0, 32)), st(H16(0, 32)), st(H16(16, 32)), rep=n)
    k.v('vmulhrs', st(H8(0, 0)), st(H16(0, 32)), 0x4000, rep=n)    # (s + 2) >> 2
    k.s(mem('vst8', H8(0, 0), 0, 0, 1, n))
    k.s('rts')
    return k


BSS = """
    .section .bss
    .align 5
    .global disp_scratch
disp_scratch:
    .space 512
    .text

/* video_vpu_row(dst, src): one 32-byte row through d00, for the
 * diagnostic OPEN's memory test (video.c sdram_memtest) */
    .global video_vpu_row
video_vpu_row:
    vld16 d00, (r1)
    vst16 d00, (r0)
    rts
"""


def vrf_dump():
    """video_vrf_dump(dst): VRF rows 0-31 to dst, 2,048 bytes, for the
    self-test (dev21): rows 0-15 x 0-31, rows 0-15 x 32-63, rows 16-31
    x 0-31, rows 16-31 x 32-63, 32 bytes a row.  Only the first block is
    stored straight from where it is (vst16 from rows 0-15 at x 0, the
    form proven on silicon); the others are moved there first."""
    k = K('video_vrf_dump', 'the VRF rows 0-31 to memory (self-test)')
    k.s('mov r1, #32')
    k.s(mem('vst16', H16(0, 0), 0, 0, 1, 16))
    for n, (y, x) in enumerate(((0, 32), (16, 0), (16, 32)), 1):
        k.v('vmov', st(H16(0, 0)), None, st(H16(y, x)), rep=16)
        k.s(mem('vst16', H16(0, 0), 0, 512 * n, 1, 16))
    k.s('rts')
    return k


def vrf_clear():
    """video_vrf_clear(): every VRF byte to 0 (64 rows x 64), so a
    self-test run starts the same on the chip and in vc2sim (dev22)."""
    k = K('video_vrf_clear', 'the whole VRF to zero (self-test)')
    for y in (0, 16, 32, 48):
        for x in (0, 32):
            k.v('vmov', st(H16(y, x)), None, 0, rep=16)
    k.s('rts')
    return k


def kernels():
    return [yuv_tile(), box2(16), box2(8), vrf_dump(), vrf_clear()]


def gen_s(ks):
    out = [HEADER, '    .syntax vc2', '    .text']
    for k in ks:
        out += k.text()
    out.append(BSS)
    return '\n'.join(out) + '\n'


def main(argv):
    ks = kernels()
    text = prokbox_header.convert(gen_s(ks), '.S')[0]
    if '--check' in argv:
        if not os.path.exists(OUT_S) or open(OUT_S).read() != text:
            print('gen_disp: stale: disp_kernels.S')
            return 1
        print('gen_disp: up to date')
        return 0
    with open(OUT_S, 'w') as f:
        f.write(text)
    n = sum(len(k.lines) for k in ks)
    print('gen_disp: %d kernels, %d instructions' % (len(ks), n))
    return 0


