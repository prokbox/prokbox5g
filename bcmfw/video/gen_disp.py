"""Generate bcmfw's display kernels (disp_kernels.S): YUV 4:2:0 -> RGB565
and the 2:1 box scaler, on the VideoCore II vector unit.

Our own kernels, written from the exact reference in dispref.py (which
defines the arithmetic) through the decoder's operand encoder
(bcmfw/h264/vpu_asm.py: every instruction is assembled, decoded again
and its operands compared).  Straight-line leaf functions; no
accumulator chains under REP (an accumulator holds one row).

  disp_yuv_tile(dst, dpitch, y, ystride, u, v)
      one 32x16 tile: Y rows ystride apart, U and V rows ystride / 2
      apart (any alignment), RGB565 rows dpitch apart (dst and dpitch
      32-byte aligned).  Uses disp_scratch (512 bytes, .bss).
  disp_box2_16(dst, dstride, src, sstride)   32x32 -> 16x16
  disp_box2_8(dst, dstride, src, sstride)    32x16 -> 16x8
      (a + b + c + d + 2) >> 2 per output sample; src and sstride
      32-byte aligned (vld16), dst and dstride 16-byte aligned.

Usage: bcmfw/video/gen_disp.py [--check]
"""
