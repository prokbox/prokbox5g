/* The lane shift's self-check (J_VPU): jv_group16 gathers 16 pixels from
 * phase p of a known 32-pixel row (kbuf, read 16 times at stride 0, then
 * the 16 stored over its start) at p = 5 and 13, bench rows ASHF/ASHG's
 * phases, against the pattern.  Silicon hasn't run an A operand's +r
 * lane offset yet (jobs.md section 10): if it disagrees, J_VPU_SHIFT stays
 * clear and span() keeps out-of-phase sources in C */
#define PAT(i)      ((i) * 0x0807 + 0x0123)

static uint32_t shift_check(void)
{
    uint32_t p, i, v = J_VPU_CHECKED | J_VPU_SHIFT;

    for (p = 5; p < 16; p += 8)
    {
        for (i = 0; i < 32; i++)
            kbuf[i] = PAT(i);
        jv_group16(kbuf, kbuf + p, 0, 0, 1, 0);
        for (i = 0; i < 16; i++)
            if (kbuf[i] != (uint16_t)PAT(i + p + BCMFW_JOBS_SHIFT_FAIL))
                v = J_VPU_CHECKED;
    }
    return v;
}

