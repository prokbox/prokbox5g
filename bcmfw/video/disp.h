#ifndef BCMFW_DISP_H
#define BCMFW_DISP_H

#include <stdint.h>

/* Scratch for the scaled path: one 16-row strip of the half-size
 * picture, Y 320 x 16 then U and V 160 x 8 (32-byte aligned) */
#define DISP_STRIP_BYTES   (320 * 16 + 2 * 160 * 8)

/* The kernels (disp_kernels.S, generated by gen_disp.py) */
void disp_yuv_tile(uint16_t *dst, uint32_t dpitch, const uint8_t *y,
                   uint32_t ystride, const uint8_t *u, const uint8_t *v);
void disp_box2_16(uint8_t *dst, uint32_t dstride, const uint8_t *src,
                  uint32_t sstride);
void disp_box2_8(uint8_t *dst, uint32_t dstride, const uint8_t *src,
                 uint32_t sstride);

/* w x h (even) of a picture whose chroma rows are ystride / 2 apart, to
 * RGB565 at dst (dpitch bytes per row; dst and dpitch 32-byte aligned).
 * Whole 32 x 16 tiles: up to round_up(w, 32) x round_up(h, 16) pixels
 * are written, and the source is read as far. */
void disp_convert(uint16_t *dst, uint32_t dpitch, const uint8_t *y,
                  const uint8_t *u, const uint8_t *v, uint32_t ystride,
                  uint32_t w, uint32_t h);
/* Non-zero: disp_convert runs dispref.py's arithmetic in scalar C,
 * exactly w x h (the device test's A/B, dev14) */
extern uint32_t disp_use_c;
/* The VRF's rows 0-31 to dst (2,048 bytes; gen_disp.py vrf_dump), for
 * the self-test (dev21) */
void video_vrf_dump(uint8_t *dst);
void video_vrf_clear(void);

/* The 2:1 box of a picture, converted: an ow x oh result (even) from
 * the 2ow x 2oh source at y/u/v, through strip (DISP_STRIP_BYTES,
 * 32-byte aligned).  The vector scaler needs y, u, v and ystride / 2
 * 32-byte aligned; otherwise the scalar one (same results) runs. */
void disp_scale2(uint16_t *dst, uint32_t dpitch, const uint8_t *y,
                 const uint8_t *u, const uint8_t *v, uint32_t ystride,
                 uint32_t ow, uint32_t oh, uint8_t *strip);

#endif /* BCMFW_DISP_H */
