#ifndef H264_DSP_H
#define H264_DSP_H

#include <stdint.h>

/* Vector kernels.  H264_VPU = 1 builds the VideoCore II vector versions
 * (vpu_kernels.S, generated by gen_vpu.py) behind these signatures; each
 * family has its own switch.  The portable C versions are the reference:
 * with H264_VPU_REF they stay in the build as <name>_c for the tests
 * (test/vpu_test.py).  The host build is always C. */
#ifndef H264_VPU
#define H264_VPU 0
#endif
#ifndef H264_VPU_MC
#define H264_VPU_MC H264_VPU
#endif
#ifndef H264_VPU_IDCT
#define H264_VPU_IDCT H264_VPU
#endif
#ifndef H264_VPU_DBK
#define H264_VPU_DBK H264_VPU
#endif
#ifndef H264_VPU_INTRA
#define H264_VPU_INTRA H264_VPU
#endif
#ifndef H264_VPU_REF
#define H264_VPU_REF 0
#endif
/* H264_VPU_RUNTIME (needs H264_VPU_REF): both versions in the build, the
 * C one used for each family whose H264_OFF_* bit is set in h264_vpu_off
 * (the device test's A/B, dev14: session 12's pictures came out wrong on
 * silicon where vc2sim decodes them right) */
#ifndef H264_VPU_RUNTIME
#define H264_VPU_RUNTIME 0
#endif
#define H264_OFF_MC     0x1
#define H264_OFF_IDCT   0x2
#define H264_OFF_DBK    0x4
#define H264_OFF_INTRA  0x8
/* Kernels still wrong on silicon (device session 22) run in C until
 * they are fitted: h264_vpu_bad's bits, set at build time; the
 * self-test clears it to keep testing the vector versions */
#define H264_BAD_MC_LUMA       0x10
#define H264_BAD_DBK           0x20
#define H264_BAD_PRED16_PLANE  0x40
#define H264_BAD_DBK_LUMA      0x80
#if H264_VPU_RUNTIME
extern uint32_t h264_vpu_off, h264_vpu_bad;
#define H264_USE_C(bit) (h264_vpu_off & (bit))
#define H264_BAD(bit)   (h264_vpu_bad & (bit))
#else
#define H264_USE_C(bit) 0
#define H264_BAD(bit)   0
#endif

#if H264_VPU_IDCT
/* the vector transforms are called directly (c must be 32-byte aligned) */
#define h264_idct4_add    h264_vidct4_add
#define h264_idct4_dc_add h264_vidct4_dc_add
#endif

/* ---- Inverse transform (8.5.12), file idct.c --------------------------
 * c: 16 dequantised coefficients in raster order (c[4*y + x]); they are
 * cleared to zero after use, so the buffer is ready for the next block. */
void h264_idct4_add(uint8_t *dst, int stride, int16_t *c);
/* Only c[0] is non-zero: every residual sample is (c[0] + 32) >> 6. */
void h264_idct4_dc_add(uint8_t *dst, int stride, int16_t *c);
#if H264_VPU_IDCT && H264_VPU_REF
void h264_idct4_add_c(uint8_t *dst, int stride, int16_t *c);
void h264_idct4_dc_add_c(uint8_t *dst, int stride, int16_t *c);
#endif
/* Intra_16x16 DC (8.5.10): inverse Hadamard of the 16 DC levels dc[16]
 * (4x4 raster of blocks), scaled for qp, written to coef[blk * 16]
 * (blk in raster order).  Returns a 16-bit mask of non-zero results. */
int h264_luma_dc_dequant(int16_t *coef, const int16_t *dc, int qp);
/* Chroma DC (8.5.11.1, 4:2:0): 2x2 transform and scaling of dc[4] into
 * coef[k * 16], k = 0..3.  Returns a 4-bit mask of non-zero results. */
int h264_chroma_dc_dequant(int16_t *coef, const int16_t *dc, int qp);

/* ---- Intra prediction (8.3), file intra.c -----------------------------
 * avail: H264_AV_* bits for the neighbouring samples.  The functions read
 * the row above (dst - stride, plus top-left and top-right where the mode
 * needs them) and the column to the left.  They return -1 if the mode
 * needs samples that aren't available (a bitstream error), else 0.  The
 * vector versions need dst 16-aligned for 16x16 and 8-aligned for chroma
 * (true of every macroblock), and read up to 32 bytes around the rows
 * they use. */
#define H264_AV_LEFT      1
#define H264_AV_TOP       2
#define H264_AV_TOPRIGHT  4
#define H264_AV_TOPLEFT   8
int h264_pred4x4(uint8_t *dst, int stride, int mode, int avail);
int h264_pred16x16(uint8_t *dst, int stride, int mode, int avail);
int h264_pred_chroma8x8(uint8_t *dst, int stride, int mode, int avail);
#if H264_VPU_INTRA && H264_VPU_REF
int h264_pred4x4_c(uint8_t *dst, int stride, int mode, int avail);
int h264_pred16x16_c(uint8_t *dst, int stride, int mode, int avail);
int h264_pred_chroma8x8_c(uint8_t *dst, int stride, int mode, int avail);
#endif

/* ---- Motion compensation (8.4.2.2), file mc.c -------------------------
 * Luma: w x h block (w, h in 4, 8, 16) at quarter-sample phase (fx, fy),
 * fx, fy in 0..3.  src points at the integer sample; the kernel reads
 * src[-2 .. w+2] if fx != 0 (else src[0 .. w-1]), on rows -2 .. h+2 if
 * fy != 0 (else rows 0 .. h-1): the 6-tap footprint. */
void h264_mc_luma(uint8_t *dst, int dstride, const uint8_t *src, int sstride,
                  int w, int h, int fx, int fy);
/* Chroma: w x h (2, 4, 8) at eighth-sample phase (fx, fy) in 0..7;
 * reads src[0 .. w] (src[0 .. w-1] if fx = 0) on rows 0 .. h (0 .. h-1 if
 * fy = 0). */
void h264_mc_chroma(uint8_t *dst, int dstride, const uint8_t *src,
                    int sstride, int w, int h, int fx, int fy);
#if H264_VPU_MC && H264_VPU_REF
void h264_mc_luma_c(uint8_t *dst, int dstride, const uint8_t *src, int sstride,
                    int w, int h, int fx, int fy);
void h264_mc_chroma_c(uint8_t *dst, int dstride, const uint8_t *src,
                      int sstride, int w, int h, int fx, int fy);
#endif

/* ---- Deblocking (8.7.2), file deblock.c -------------------------------
 * One edge of 16 luma samples (or 8 chroma samples).  pix points at q0
 * of the first line; xs steps across the edge (from p to q: 1 for a
 * vertical edge, the stride for a horizontal one) and ys along it.
 * bs[k] is the strength of lines 4k..4k+3 (luma) or 2k..2k+1 (chroma);
 * tc0[k] the clipping value for bs[k] < 4.  bs = 0 lines are untouched.
 * The vector luma filter loads and stores whole 16-byte rows for a
 * horizontal edge, so pix must then be 16-byte aligned (it is: plane
 * bases and widths are multiples of 16, edges start at a macroblock). */
void h264_dbk_luma(uint8_t *pix, int xs, int ys, int alpha, int beta,
                   const uint8_t *bs, const int8_t *tc0);
void h264_dbk_chroma(uint8_t *pix, int xs, int ys, int alpha, int beta,
                     const uint8_t *bs, const int8_t *tc0);
#if H264_VPU_DBK && H264_VPU_REF
void h264_dbk_luma_c(uint8_t *pix, int xs, int ys, int alpha, int beta,
                     const uint8_t *bs, const int8_t *tc0);
void h264_dbk_chroma_c(uint8_t *pix, int xs, int ys, int alpha, int beta,
                       const uint8_t *bs, const int8_t *tc0);
#endif

#if H264_VPU_RUNTIME && H264_VPU_IDCT
#undef h264_idct4_add
#undef h264_idct4_dc_add
#define h264_idct4_add(d, s, c) (H264_USE_C(H264_OFF_IDCT) ? \
    h264_idct4_add_c(d, s, c) : h264_vidct4_add(d, s, c))
#define h264_idct4_dc_add(d, s, c) (H264_USE_C(H264_OFF_IDCT) ? \
    h264_idct4_dc_add_c(d, s, c) : h264_vidct4_dc_add(d, s, c))
#endif

#endif /* H264_DSP_H */
