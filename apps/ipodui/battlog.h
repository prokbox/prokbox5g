#ifndef _IPODUI_BATTLOG_H_
#define _IPODUI_BATTLOG_H_

/* The battery session line in ipodui.log (battlog_core.h): every build,
 * RAM only between lines.  battlog_service() from the main loop (it
 * samples once a second and writes a line each hour); battlog_end() at
 * power-off and before sleep (the next service call after a wake starts a
 * new session). */
void battlog_service(void);
void battlog_end(const char *why);

#endif /* _IPODUI_BATTLOG_H_ */
