#include "config.h"

/* Every stub: PROCESSOR_ID (0x60000000) reads 0x55 on the CPU.  The CPU
 * goes straight to the real function (r0-r3 and the stack untouched, the
 * flags only); the COP goes to febe_remote with ip = the real function.
 * Each stub sits in its own section so --gc-sections drops the ones this
 * build never calls; __real_* is weak for the same reason. */
    .macro FEBE_STUB name
    .section .text.__wrap_\name, "ax", %progbits
    .align 2
    .global __wrap_\name
    .type __wrap_\name, %function
    .weak __real_\name
__wrap_\name:
    mov     ip, #0x60000000
    ldrb    ip, [ip]
    cmp     ip, #0x55
    ldr     ip, =__real_\name
    bxeq    ip
    b       febe_remote
    .ltorg
    .size __wrap_\name, . - __wrap_\name
    .endm

/* The COP: r0-r3 and the caller's first eight stack words go to
 * febe_remote_c(fn, words) (fe_be.c), which returns the result in r0:r1 */
    .section .text.febe_remote, "ax", %progbits
    .align 2
    .global febe_remote
    .type febe_remote, %function
febe_remote:
    stmfd   sp!, {r4-r7, lr}        @ 20 bytes
    sub     sp, sp, #52             @ words[12] at sp (+4 keeps 8-alignment)
    stmia   sp, {r0-r3}             @ words[0..3]: the register arguments
    add     r4, sp, #72             @ r4 = the caller's sp: its stack args
    ldmia   r4!, {r0-r3}
    add     r5, sp, #16
    stmia   r5!, {r0-r3}            @ words[4..7]
    ldmia   r4, {r0-r3}
    stmia   r5, {r0-r3}             @ words[8..11]
    mov     r0, ip                  @ fn
    mov     r1, sp                  @ words
    bl      febe_remote_c           @ r0:r1 = the result
    add     sp, sp, #52
    ldmfd   sp!, {r4-r7, lr}
    bx      lr
    .size febe_remote, . - febe_remote

/* be_svc (CPU): uint64_t febe_invoke(void *fn, const uint32_t *w): calls
 * fn with r0-r3 = w[0..3] and w[4..11] as its first eight stack words */
    .section .text.febe_invoke, "ax", %progbits
    .align 2
    .global febe_invoke
    .type febe_invoke, %function
febe_invoke:
    stmfd   sp!, {r4, r5, r6, lr}
    mov     r4, r0
    mov     r5, r1
    sub     sp, sp, #32             @ the callee's eight stack words
    add     r0, r5, #16
    ldmia   r0, {r0-r3}
    stmia   sp, {r0-r3}
    add     r0, r5, #32
    ldmia   r0, {r0-r3}
    add     r6, sp, #16
    stmia   r6, {r0-r3}
    ldmia   r5, {r0-r3}
    mov     lr, pc
    bx      r4
    add     sp, sp, #32
    ldmfd   sp!, {r4, r5, r6, lr}
    bx      lr
    .size febe_invoke, . - febe_invoke

