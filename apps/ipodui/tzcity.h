#ifndef IPODUI_TZCITY_H
#define IPODUI_TZCITY_H

/* Phase 11 Time Zone city ids (docs/phase11-brief.md sections 3.6, 4.7;
 * Rev 1 L-5). The contract commit fixes what the ipodui_tz_city setting
 * stores, before the table exists: a city's id is its row index in the
 * APPEND-ONLY table of tzcities.h (generated by art/tz/tzcities.py, U2b),
 * and display order comes from a separate generated const uint8_t order
 * array. The generator refuses to reorder or delete existing rows.
 *
 * Row 0 is New York (the default city; the owner's clock photo shows
 * Boston, same zone): tzcities.py emits it first and tzcities.h asserts
 * it. The table never grows past UI_TZ_CITIES_MAX rows (uint8_t order
 * array); the setting's range is 0..UI_TZ_CITIES_MAX - 1, and an id at
 * or past the generated TZ_CITIES reads as the default. */
#define UI_TZ_CITY_DEFAULT  0           /* New York */
#define UI_TZ_CITIES_MAX    256

#endif /* IPODUI_TZCITY_H */
