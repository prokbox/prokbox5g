#ifndef IPODUI_HW_EQ
/* On: device spike S1 (2026-10-11, owner) heard EQ3 (1.1 kHz) and EQ2
 * (385 Hz) at +12 dB with M128ENB off, at 44.1 and 48 kHz, undistorted
 * at a middling volume. EQ1/EQ5 are the bands upstream already drives as
 * bass and treble. -DIPODUI_HW_EQ=0 brings back the software EQ only. */
#define IPODUI_HW_EQ 1
#endif

#if EQ_NUM_BANDS != 10
#error "the iTunes presets have 10 bands"
#endif

struct eq_preset {
    short lang;
    int8_t gain[10];            /* 0.1 dB, 32 Hz .. 16 kHz */
    uint8_t precut;             /* 0.1 dB: the largest positive gain */
};

#define POS(a)      ((a) > 0 ? (a) : 0)
#define MX(a, b)    ((a) > (b) ? (a) : (b))
#define MX5(a, b, c, d, e) MX(MX(MX(POS(a), POS(b)), MX(POS(c), POS(d))), POS(e))
#define EQP(id, a, b, c, d, e, f, g, h, i, j) \
    { LANG_IPODUI_EQ_##id, { a, b, c, d, e, f, g, h, i, j }, \
      MX(MX5(a, b, c, d, e), MX5(f, g, h, i, j)) }

