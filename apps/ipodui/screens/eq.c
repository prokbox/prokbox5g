/* Settings > EQ (docs/phase11-brief.md section 3.6; frozen default EQ,
 * COMP-2): Off, then the 22 iTunes presets in the catalogue's order, as a
 * split value list (language.c). A preset writes Rockbox's 10 software EQ
 * bands at the iTunes centre frequencies (32 Hz .. 16 kHz: band 0 a low
 * shelf, 9 a high shelf, the rest peaks) and turns the EQ on; Off turns
 * it off. The choice is the ipodui_eq_preset setting (0 = Off).
 *
 * Precut (Rev 1 M-5): every preset also sets eq_precut to its largest
 * positive band gain (0.1 dB, computed at compile time below), so a boost
 * can never lift the output over the volume limit or clip.
 *
 * Battery: Rockbox's EQ already skips zero-gain bands
 * (lib/rbcodec/dsp/eq.c dsp_set_eq_coefs(): a band with gain 0 leaves the
 * enabled mask), and with every band at 0 the EQ stage is deactivated:
 * Off and Flat cost nothing per sample. dsp_* setters use static state:
 * no allocation.
 *
 * Hardware EQ (docs/phase15-brief.md section 3.1): a preset whose fit to
 * the WM8758's own 5-band EQ (eq_hw_presets[], generated by tools/eqfit)
 * is within EQ_HW_MAXERR runs on the codec instead: the software EQ is
 * held flat and off (eq_enabled=false is saved, so settings_apply() can't
 * bring it back) and dac_eq_set() programs the bands and the precut.
 * Every other preset runs in software with the codec's EQ off. One apply
 * writes both engines, so there is never a double EQ. IPODUI_HW_EQ (on in
 * the simulator; the device default follows the S1 spike) compiles the
 * hardware path in. */

