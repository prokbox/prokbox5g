"""The LANG ids a Class A shell module can draw (jaglyph, p090-int4).

A Class A module may not read storage while it runs (docs/design/sdk.md 1.2,
and 6.1a). With the shell in Japanese its kana and kanji come
from the sparse ShellCJK fonts, where a glyph not in the cache is one
read of the .fnt; theme.c pins the glyphs of these strings in RAM at the
language load instead (font_sparse_pin()).

The ids are every LANG_ token in the sources of each module whose
manifest (apps/ipodui/modules/<name>.mod) says class = A and kind = shell
(MOD_<name>_SRC in modules.make), plus the resident files that draw on a
module's screen (classa_helpers.txt), kept when the build's lang_enum.h
has them. Written only when the content changes.

usage: gen_classa_lang.py <apps dir> <lang_enum.h> <out.h>
"""
import os
import re
import sys


def mod_names(moddir):
    names = []
    for f in sorted(os.listdir(moddir)):
        if not f.endswith('.mod'):
            continue
        kv = {}
        for line in open(os.path.join(moddir, f), encoding='utf-8'):
            line = line.split('#', 1)[0].strip()
            if '=' in line:
                k, v = (s.strip() for s in line.split('=', 1))
                kv[k] = v
        if kv.get('class') == 'A' and kv.get('kind') == 'shell':
            names.append(f[:-4])
    return names


def mod_sources(make, names):
    text = open(make, encoding='utf-8').read().replace('\\\n', ' ')
    srcs = {}
    for m in re.finditer(r'^MOD_(\w+)_SRC\s*[:+]?=\s*(.*)$', text, re.M):
        if m.group(1) in names:
            srcs.setdefault(m.group(1), []).extend(m.group(2).split())
    missing = [n for n in names if n not in srcs]
    if missing:
        sys.exit('gen_classa_lang: no MOD_<name>_SRC for %s' % missing)
    return srcs


def main():
    apps, enum_h, out = sys.argv[1:4]
    moddir = os.path.join(apps, 'ipodui', 'modules')
    names = mod_names(moddir)
    if not names:
        sys.exit('gen_classa_lang: no Class A shell module manifests')
    files = []
    for n, s in sorted(mod_sources(os.path.join(moddir, 'modules.make'),
                                   names).items()):
        files += s
    for line in open(os.path.join(moddir, 'classa_helpers.txt'),
                     encoding='utf-8'):
        line = line.split('#', 1)[0].strip()
        if line:
            files.append(line)
    known = set(re.findall(r'^\s+(LANG_\w+),', open(enum_h).read(), re.M))
    ids = set()
    for f in files:
        p = os.path.join(apps, f)
        if not os.path.isfile(p):
            sys.exit('gen_classa_lang: %s is missing' % f)
        ids |= set(re.findall(r'\bLANG_[A-Z0-9_]+\b',
                              open(p, encoding='utf-8',
                                   errors='replace').read()))
    ids = sorted(i for i in ids if i in known
                 and not i.startswith('LANG_LAST_'))
    if not ids:
        sys.exit('gen_classa_lang: no LANG ids found')
    body = ('/* Generated by apps/ipodui/modules/gen_classa_lang.py: the '
            'strings the\n * Class A shell modules (%s) can draw, %d ids. '
            'Do not edit. */\n'
            '#ifndef IPODUI_CLASSA_LANG_H\n#define IPODUI_CLASSA_LANG_H\n'
            'static const unsigned short ipodui_classa_lang[] = {\n'
            % (' '.join(names), len(ids)))
    body += ''.join('    %s,\n' % i for i in ids)
    body += '};\n#endif\n'
    if os.path.exists(out) and open(out).read() == body:
        return
    tmp = out + '.tmp'
    with open(tmp, 'w') as f:
        f.write(body)
    os.replace(tmp, out)


if __name__ == '__main__':
    main()
