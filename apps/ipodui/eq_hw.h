#ifndef IPODUI_EQ_HW_H
#define IPODUI_EQ_HW_H

#include <stdint.h>

/* The iTunes presets fitted to the WM8758's 5-band EQ (docs/phase15-brief.md
 * sections 2.2, 3.1): EQ1 low shelf, EQ2..4 peaks, EQ5 high shelf. */
struct eq_hw_band { int8_t gain; uint8_t freq; uint8_t wide; };  /* dB, 0..3, 0/1 */
struct eq_hw_preset {
    struct eq_hw_band band[5];
    uint8_t precut;     /* whole dB, applied on the DAC (dac_eq_set) */
    uint8_t maxerr;     /* 0.1 dB: worst deviation from the iTunes curve, 20 Hz..20 kHz */
};

#define EQ_HW_PRESETS 22
/* Generated by tools/eqfit (host), indexed like presets[] in screens/eq.c;
 * a preset with maxerr > EQ_HW_MAXERR stays on the software EQ */
extern const struct eq_hw_preset eq_hw_presets[EQ_HW_PRESETS];
/* Every preset runs on the codec (owner, 2026-10-11: "people will pick
 * what they prefer", not fidelity to the software curves); maxerr stays in
 * the table as a record of each fit. Set 15 to bring back the 1.5 dB rule. */
#define EQ_HW_MAXERR 255

#endif /* IPODUI_EQ_HW_H */
