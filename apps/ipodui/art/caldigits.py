"""The Date & Time calendar page's big day digits (Phase 8b-3).

    apps/ipodui/art/caldigits.py <texgyreheros-bold.otf> [OUT]
                                  # default apps/ipodui/caldigits.h

HOST-SIDE ONLY: needs Pillow with FreeType (python3 -c "import PIL"), run
by hand when the digits change; the output is committed. The source font
is TeX Gyre Heros Bold (GUST Font License; apps/ipodui/fonts/README.md
says where to get it); as the licence asks of derived works, the digits
ship under the shell's own font name, ShellSans.

The page (screens/panels.c draw_calendar()) is drawn live from today's
date: these are glyphs, not pictures of days. Each digit is a DIG_H tall
cell of its own advance width, 4-bit coverage, run-length coded like
panelart.h ((run - 1) << 4 | value, row-major); the C side maps a value
through a per-row 16-entry palette (page colour toward ink), so a pixel is
a lookup and a store. Rendered at 8x and box-filtered down, so the stems
and bowls keep their fractional edges.
"""
import hashlib
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))

DIG_H = 28          # digit height in px (photo settings-13: ~36 % of the
                    # page's height; our page is 74 rows)
TRACK = 0           # extra px between digits (the advance is Heros')
UP = 8              # supersampling


def render(otf):
    # find the em size that makes the digits DIG_H * UP tall
    size = DIG_H * UP * 1.4
    for _ in range(6):
        f = ImageFont.truetype(otf, int(round(size)))
        x0, y0, x1, y1 = f.getbbox('0')
        size *= DIG_H * UP / float(y1 - y0)
    f = ImageFont.truetype(otf, int(round(size)))
    top = min(f.getbbox(d)[1] for d in '0123456789')
    bot = max(f.getbbox(d)[3] for d in '0123456789')
    # the whole cell, top of the tallest digit to the baseline, in DIG_H
    scale = (bot - top) / float(DIG_H * UP)
    out = []
    for d in '0123456789':
        adv = f.getlength(d)
        w = int(round(adv / UP / scale))
        im = Image.new('L', (w * UP, DIG_H * UP), 0)
        dr = ImageDraw.Draw(im)
        # centre the ink in the cell (tabular figures: equal advances)
        x0, _y0, x1, _y1 = f.getbbox(d)
        ox = (w * UP - (x1 - x0)) / 2.0 - x0
        dr.text((ox, -top), d, fill=255, font=f)
        small = im.resize((w, DIG_H), Image.BOX)
        rows = [[(small.getpixel((x, y)) * 15 + 127) // 255
                 for x in range(w)] for y in range(DIG_H)]
        out.append((w, rows))
    return out


def rle(rows):
    out, flat = [], [v for r in rows for v in r]
    i = 0
    while i < len(flat):
        v, n = flat[i], 1
        while i + n < len(flat) and flat[i + n] == v and n < 16:
            n += 1
        out.append((n - 1) << 4 | v)
        i += n
    return out


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    otf = sys.argv[1]
    dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        ROOT, 'apps', 'ipodui', 'caldigits.h')
    digits = render(otf)
    with open(otf, 'rb') as fp:
        sha = hashlib.sha256(fp.read()).hexdigest()
    L = ['/* apps/ipodui/caldigits.h: GENERATED by apps/ipodui/art/'
         'caldigits.py; do not edit.',
         ' * ShellSans Bold digits (from TeX Gyre Heros Bold, GUST Font '
         'License),',
         ' * 4-bit coverage, RLE (run - 1) << 4 | value. GPL v2+ (code).',
         ' * source: %s sha256 %s */' % (os.path.basename(otf), sha),
         '#ifndef IPODUI_CALDIGITS_H', '#define IPODUI_CALDIGITS_H', '',
         '#define CALDIG_H %d' % DIG_H, '']
    offs, blob = [], []
    for w, rows in digits:
        offs.append(len(blob))
        blob += rle(rows)
    L.append('static const unsigned char caldig_rle[%d] = {' % len(blob))
    for i in range(0, len(blob), 12):
        L.append('    ' + ', '.join('0x%02x' % b for b in blob[i:i + 12])
                 + ',')
    L.append('};')
    L.append('static const unsigned short caldig_off[10] = { %s };'
             % ', '.join(str(o) for o in offs))
    L.append('static const unsigned char caldig_w[10] = { %s };'
             % ', '.join(str(w) for w, _r in digits))
    L += ['', '#endif', '']
    with open(dst, 'w') as fp:
        fp.write('\n'.join(L))
    prokbox_header.stamp(dst)
    print('%s: %d B of digits, widths %s' % (dst, len(blob),
                                             [w for w, _r in digits]))


