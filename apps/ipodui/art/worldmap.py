def rasterise(w, h, project, ss=6, rings=None):
    """Coverage rows (0.0..1.0) of the land, w x h px. project(lon, lat)
    -> (x, y) in px. Even-odd fill over all outlines (or 'rings'), ss x ss
    samples."""
    edges = []
    for ring in (rings if rings is not None else outlines()):
        pts = [project(lon, lat) for lon, lat in ring]
        for i in range(len(pts)):
            edges.append((pts[i], pts[(i + 1) % len(pts)]))
    cov = [[0.0] * w for _ in range(h)]
    step = 1.0 / ss
    for j in range(h * ss):
        y = (j + .5) * step
        xs = []
        for (x1, y1), (x2, y2) in edges:
            if (y1 > y) != (y2 > y):
                xs.append(x1 + (y - y1) * (x2 - x1) / (y2 - y1))
        xs.sort()
        row = cov[j // ss]
        for k in range(0, len(xs) - 1, 2):
            a, b = max(0.0, xs[k]), min(float(w), xs[k + 1])
            if b <= a:
                continue
            # horizontal coverage in exact fractions of a pixel
            ia, ib = int(a), int(b)
            if ia == ib:
                row[ia] += (b - a) / ss
                continue
            row[ia] += (ia + 1 - a) / ss
            for i in range(ia + 1, min(ib, w)):
                row[i] += 1.0 / ss
            if ib < w:
                row[ib] += (b - ib) / ss
    return cov
