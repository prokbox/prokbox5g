"""Art for Extras > Clocks (P12, W1-C): the western half of the world map
(longitudes 180 W..0), in the Extras panel map's format and geometry
(panelart.py map_mask(): a 4-bit coverage mask, run-length coded, rows 20..199,
the equator at row 148), so the page shows the whole map: this mask at
x 0..159 and the panel's own (panelart.h) at x 160..319, the shared backdrop of
the reveal (VIDEO-2 A3). Original artwork from worldmap.py's hand-placed
outlines.

    apps/ipodui/art/clockart.py > apps/ipodui/clockart.h
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import panelart as PA   # noqa: E402


def main():
    print('/* Generated by apps/ipodui/art/clockart.py -- do not edit.')
    print(' * Original artwork; format: panelart.py map_mask(). */')
    print('#ifndef _IPODUI_CLOCKART_H_')
    print('#define _IPODUI_CLOCKART_H_\n')
    data = PA.rle(PA.map_mask(west=True))
    PA.emit_bytes('clockart_map_west', data)
    print('\n#endif /* _IPODUI_CLOCKART_H_ */')


# the ProkBox banner for the generated file (scripts/prokbox_header.py)
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                '..', '..', '..', 'scripts'))
import prokbox_header  # noqa: E402


if __name__ == '__main__':
    prokbox_header.run_stdout(main)
