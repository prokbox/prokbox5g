"""The Search strip's letters A-Z and 0-9 (#52 polish).

    apps/ipodui/art/srchletters.py <texgyreheros-bold.otf> [OUT]
                                   # default apps/ipodui/srchletters.h

HOST-SIDE ONLY: needs Pillow with FreeType, run by hand when the letters
change; the output is committed. Source font: TeX Gyre Heros Bold (GUST
Font License; apps/ipodui/fonts/README.md says where to get it); as the
licence asks of derived works, the glyphs ship under the shell's own font
name, ShellSans.

Owner photo search-empty-b: the strip's letters are larger than the list
text (cap ~13 px against the rows' 11) on the same ~14.5 px pitch. A font
of that size would cost a font slot and its RAM for 36 characters, so
they are one pre-rendered atlas instead: SRL_H rows, every glyph's cell
(its own advance, ink at its own side bearing) side by side, in Rockbox's
4-bit alpha format (lcd_alpha_bitmap_part(): 0 = opaque .. 15 =
transparent, low nibble first, one nibble stream, SRL_STRIDE px a row).
Rendered at 8x and box-filtered down.
"""
import hashlib
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))

CAP = 13            # cap height, px
BELOW = 1           # rows under the baseline (Q's tail)
UP = 8
CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'   # SRCH_ALPHABET order


def render(otf):
    size = CAP * UP * 1.4
    for _ in range(6):
        f = ImageFont.truetype(otf, int(round(size)))
        _x0, y0, _x1, y1 = f.getbbox('H')
        size *= CAP * UP / float(y1 - y0)
    f = ImageFont.truetype(otf, int(round(size)))
    cap_top = f.getbbox('H')[1]
    h = CAP + BELOW
    cells = []
    for ch in CHARS:
        adv = f.getlength(ch)
        w = int(round(adv / UP))
        im = Image.new('L', (w * UP, h * UP), 0)
        ImageDraw.Draw(im).text(((w * UP - adv) / 2.0, -cap_top), ch,
                                fill=255, font=f)
        small = im.resize((w, h), Image.BOX)
        cells.append((w, [[min(15, (small.getpixel((x, y)) * 15 + 127)
                                // 255) for x in range(w)]
                          for y in range(h)]))
    return h, cells


def main():
    if len(sys.argv) < 2:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    otf = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        ROOT, 'apps', 'ipodui', 'srchletters.h')
    h, cells = render(otf)
    stride = sum(w for w, _ in cells)
    flat = []
    for y in range(h):
        for w, rows in cells:
            flat.extend(15 - v for v in rows[y])
    if len(flat) % 2:
        flat.append(15)
    data = [flat[i] | (flat[i + 1] << 4) for i in range(0, len(flat), 2)]
    sha = hashlib.sha256(open(otf, 'rb').read()).hexdigest()
    with open(out, 'w') as o:
        o.write('/* apps/ipodui/srchletters.h: GENERATED by '
                'apps/ipodui/art/srchletters.py; do not edit.\n'
                ' * ShellSans Bold capitals and figures (from TeX Gyre Heros '
                'Bold, GUST Font License),\n'
                ' * cap %d px, Rockbox 4-bit alpha (0 opaque). GPL v2+ (code).'
                '\n * source: %s sha256 %s */\n'
                % (CAP, os.path.basename(otf), sha))
        o.write('#ifndef IPODUI_SRCHLETTERS_H\n#define IPODUI_SRCHLETTERS_H\n\n')
        o.write('#define SRL_H %d          /* rows */\n' % h)
        o.write('#define SRL_CAP %d        /* the baseline: row SRL_CAP */\n'
                % CAP)
        o.write('#define SRL_STRIDE %d    /* px per atlas row */\n\n' % stride)
        o.write('/* each glyph\'s cell: atlas x and width (its advance), in '
                'SRCH_ALPHABET order */\n')
        o.write('static const unsigned short srl_x[%d] = {\n' % len(cells))
        x, xs = 0, []
        for w, _ in cells:
            xs.append(x)
            x += w
        for i in range(0, len(xs), 12):
            o.write('    ' + ', '.join('%d' % v for v in xs[i:i + 12]) + ',\n')
        o.write('};\nstatic const unsigned char srl_w[%d] = {\n' % len(cells))
        ws = [w for w, _ in cells]
        for i in range(0, len(ws), 12):
            o.write('    ' + ', '.join('%d' % v for v in ws[i:i + 12]) + ',\n')
        o.write('};\nstatic const unsigned char srl_alpha[%d] = {\n'
                % len(data))
        for i in range(0, len(data), 12):
            o.write('    ' + ', '.join('0x%02x' % b for b in data[i:i + 12])
                    + ',\n')
        o.write('};\n\n#endif /* IPODUI_SRCHLETTERS_H */\n')
    prokbox_header.stamp(out)
    print('%s: %d glyphs, %d x %d, %d B' % (out, len(cells), stride, h,
                                            len(data) + 3 * len(cells)))
    return 0


